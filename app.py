Q_WEATHER            = 0.55   # ~11 km grid model + ICAO lapse correction
Q_TERRAIN_LIDAR      = 0.95   # ICGC 5 m LiDAR DEM (2021-2023)
Q_TERRAIN_COPERNICUS = 0.70   # Copernicus DEM via Open-Meteo (~90 m)
