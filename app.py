def fetch_corine(lat, lon):
    """Query CORINE CLC 2018 WMS GetFeatureInfo. Returns (code, label)."""
    delta = 0.03
    bbox = f"{lat-delta},{lon-delta},{lat+delta},{lon+delta}"
    url = (
        "https://image.discomap.eea.europa.eu/arcgis/services/Corine/"
        "CLC2018_WM/MapServer/WMSServer"
        "?SERVICE=WMS&VERSION=1.3.0&REQUEST=GetFeatureInfo"
        "&LAYERS=13&QUERY_LAYERS=13"
        f"&CRS=EPSG:4326&BBOX={bbox}"
        "&WIDTH=100&HEIGHT=100&I=50&J=50"
        "&INFO_FORMAT=text/html"
    )
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "BoletsForecast/1.0"})
        with urllib.request.urlopen(req, timeout=12) as r:
            html = r.read().decode("utf-8", errors="replace")
        # Parse table: FID, Shape, Code_18, ...
        rows = re.findall(r"<tr>(.*?)</tr>", html, re.DOTALL)
        for row in rows[1:]:  # skip header
            cells = re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", row, re.DOTALL)
            cells = [c.strip() for c in cells]
            if len(cells) >= 3:
                code = cells[2]
                label = CORINE_CODES.get(code, f"Code {code}")
                return code, label
    except Exception:
        pass
    return "unknown", "Unknown"

# ── SoilGrids pH (fallback for mixed/unknown lithology) ──────────────────────

def fetch_soilgrids_ph(lat, lon):
    """Query SoilGrids v2 for pH at 0-5cm. Returns float or None."""
    url = (
        "https://rest.isric.org/soilgrids/v2.0/properties/query"
        f"?lon={lon}&lat={lat}&property=phh2o&depth=0-5cm&value=mean"
    )
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "BoletsForecast/1.0"})
        with urllib.request.urlopen(req, timeout=15) as r:
            d = json.loads(r.read())
        layer = d["properties"]["layers"][0]
        val   = layer["depths"][0]["values"]["mean"]
        factor = layer["unit_measure"]["d_factor"]
        return val / factor
    except Exception:
        return None

# ── Fetch all geo data for a station (cached) ────────────────────────────────

def fetch_geo(lat, lon):
    """Returns dict with soil_type, litho_text, forest_code, forest_label, ph."""
    cached = get_cached_geo(lat, lon)
    if cached:
        return cached

    # Run IGME + CORINE in parallel
    with ThreadPoolExecutor(max_workers=2) as ex:
        fut_igme   = ex.submit(fetch_igme_litho, lat, lon)
        fut_corine = ex.submit(fetch_corine, lat, lon)
        litho_text, soil_type  = fut_igme.result()
        forest_code, forest_label = fut_corine.result()

    # SoilGrids fallback only when soil type is ambiguous
    ph = None
    if soil_type in ("mixed", "unknown"):
        ph = fetch_soilgrids_ph(lat, lon)
        if ph is not None:
            if ph < 6.3:
                soil_type = "siliceous"
            elif ph > 7.0:
                soil_type = "calcareous"
            # else keep "mixed"

    result = {
        "soil_type":    soil_type,
        "litho_text":   litho_text,
        "forest_code":  forest_code,
        "forest_label": forest_label,
        "ph":           ph,
    }
    set_cached_geo(lat, lon, result)
    return result

# ── Open-Meteo weather ────────────────────────────────────────────────────────

_weather_cache = None

def _weather_cache_map():
    global _weather_cache
    if _weather_cache is None:
        try:
            with open(WEATHER_CACHE_FILE) as f:
                _weather_cache = json.load(f)
        except Exception:
            _weather_cache = {}
    return _weather_cache

def _weather_cache_save():
    try:
        with open(WEATHER_CACHE_FILE, "w") as f:
            json.dump(_weather_cache_map(), f)
    except Exception:
        pass

def fetch_weather(lat, lon):
    key = f"{round(lat, 2)},{round(lon, 2)}"
    cache = _weather_cache_map()
    hit = cache.get(key)
    now = time.time()
    if hit and (now - hit.get("t", 0)) < WEATHER_TTL:
        return hit["daily"]

    params = _weather_params(lat, lon)
    url = "https://api.open-meteo.com/v1/forecast?" + urllib.parse.urlencode(params)
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "BoletsForecast/1.0"})
        with urllib.request.urlopen(req, timeout=15) as r:
            daily = json.loads(r.read())["daily"]
        cache[key] = {"t": now, "daily": daily}
        _weather_cache_save()
        return daily
    except Exception:
        # Serve stale cache when the provider is rate-limited or down, so the
        # app degrades gracefully instead of returning empty data.
        if hit:
            return hit["daily"]
        raise


def _weather_params(lat, lon):
    return {
        "latitude":  lat,
        "longitude": lon,
        "daily": ",".join([
            "precipitation_sum",
            "temperature_2m_max",
            "temperature_2m_min",
            "windspeed_10m_max",
            "relative_humidity_2m_max",
        ]),
        "past_days":     14,
        "forecast_days": 7,
        "timezone":      "Europe/Madrid",
    }


def lapse_correct(daily, ref_alt_m, target_alt_m):
    """Move the daily temperature arrays from `ref_alt_m` to `target_alt_m`.

    Temperature falls with altitude at the standard environmental lapse rate
    (~6.5 °C/km). Returns a copy of `daily` with `temperature_2m_max` and
    `temperature_2m_min` shifted by `(target - ref) × 6.5 °C/km`; a higher target
    altitude is colder, a lower one warmer. Precipitation, wind and humidity are
    left untouched because they do not follow a simple lapse relationship and
    inventing one would fabricate data.
    """
    if ref_alt_m is None or target_alt_m is None:
        return daily
    try:
        d_t = (float(target_alt_m) - float(ref_alt_m)) * LAPSE_RATE_C_PER_M
    except (TypeError, ValueError):
        return daily
    if abs(d_t) < 0.05:  # < 0.05 °C is below reporting precision — no-op
        return daily
    out = dict(daily)
    for var in ("temperature_2m_max", "temperature_2m_min"):
        arr = out.get(var)
        if isinstance(arr, list):
            out[var] = [round(v - d_t, 2) if isinstance(v, (int, float)) else v
                        for v in arr]
    return out


def fetch_weather_batch(coords):
    """Fetch weather for many coordinates in ONE Open-Meteo call.

    `coords` is a list of (lat, lon). Returns a dict keyed by the exact
    (lat, lon) tuple → ``{"daily": payload, "elevation": metres}``, where
    `elevation` is the model/grid altitude Open-Meteo used for that coordinate
    (needed for the lapse-rate correction in `score_zone`). Coordinates already
    cached for today are reused; on a provider error, stale cache is served where
    available and the coordinate is simply absent from the result otherwise.

    Open-Meteo returns a single JSON object for one coordinate and a JSON
    *array* of objects for several; both are normalised here. Each location
    carries its own `daily` and `elevation`.
    """
    cache = _weather_cache_map()
    now = time.time()
    today = date.today().isoformat()
    result = {}
    to_fetch = []  # (lat, lon, rounded_key)

    for lat, lon in coords:
        key = f"{round(lat, 2)},{round(lon, 2)}"
        hit = cache.get(key)
        if (hit and hit.get("date") == today
                and (now - hit.get("t", 0)) < WEATHER_TTL):
            result[(lat, lon)] = {"daily": hit["daily"],
                                  "elevation": hit.get("elevation")}
        else:
            to_fetch.append((lat, lon, key))

    if not to_fetch:
        return result

    try:
        params = _weather_params(
            ",".join(str(lat) for lat, _, _ in to_fetch),
            ",".join(str(lon) for _, lon, _ in to_fetch),
        )
        url = "https://api.open-meteo.com/v1/forecast?" + urllib.parse.urlencode(params)
        req = urllib.request.Request(url, headers={"User-Agent": "BoletsForecast/1.0"})
        with urllib.request.urlopen(req, timeout=20) as r:
            data = json.loads(r.read())
        # Normalise: one coordinate → dict, several → list of dicts.
        locations = data if isinstance(data, list) else [data]
        for (lat, lon, key), loc in zip(to_fetch, locations):
            daily = loc.get("daily", {})
            elevation = loc.get("elevation")
            # `setdefault` + update (not reassign) so the Phase-4.3 water-balance
            # fields (`w_daily`, `w_date`, `w_t`) stored on the same key survive
            # a mid-day weather refresh.
            cache.setdefault(key, {}).update({
                "t": now, "date": today, "daily": daily, "elevation": elevation,
            })
            result[(lat, lon)] = {"daily": daily, "elevation": elevation}
        _weather_cache_save()
    except Exception:
        # Degrade: serve stale cache for any miss that has one.
        for lat, lon, key in to_fetch:
            hit = cache.get(key)
            if hit:
                result[(lat, lon)] = {"daily": hit["daily"],
                                      "elevation": hit.get("elevation")}
    return result

# ── Soil water balance and drought index (Phase 4.3) ─────────────────────────
#
# The 7-day rain total alone cannot say whether the soil is actually moist: a
# wet week after a dry summer leaves a dry soil that absorbs the first rains,
# and a long wet season keeps fruiting alive through short dry spells. This
# section tracks precipitation minus reference evapotranspiration (P − ET0)
# over 14/30/60/90-day windows ending today, derives a bounded recharge index
# (the documented FAO-56 "soil as a reservoir" concept, normalised by an
# explicit storage cap — see README "Soil water balance and drought index"),
# and — as a documented modelling choice — scales each species' rain score
# term by that index (drought damps, recharge boosts; per-species sensitivity
# from the documented `rain_trigger_mm`).
#
# Data: Open-Meteo serves `et0_fao_evapotranspiration` (FAO-56 reference ET,
# mm/day) as a daily variable with `past_days` up to 92 (verified live
# 2026-11-08). The ET0 history in the forecast API currently starts ~59 days
# back, so the 60/90-day windows are partially covered until more history
# accumulates; every window records the number of days actually used and a
# window with no ET0 at all yields no water block (nothing is fabricated).

WATER_PAST_DAYS = 92
WATER_TTL = 24 * 3600       # a "today"-stamped P−ET0 series is stable all day
WATER_WINDOWS_DAYS = (14, 30, 60, 90)
# Recharge-index normalisation cap. FAO-56 (Allen et al. 1998, ch. 8) treats
# the root zone as a bounded reservoir whose total available water (TAW) is
# typically ~40–60 mm for shallow and >140 mm for deep soils (Table 19 ranges).
# 100 mm is the chosen representative forest-soil storage: a ±100 mm net
# imbalance over the recharge window saturates the index. Modelling choice,
# not field-verified per zone (see README).
SOIL_STORAGE_CAP_MM = 100.0


def _water_params(lat, lon):
    return {
        "latitude":  lat,
        "longitude": lon,
        "daily":     "precipitation_sum,et0_fao_evapotranspiration",
        "past_days":     WATER_PAST_DAYS,
        "forecast_days": 7,
        "timezone":      "Europe/Madrid",
    }


def fetch_water_batch(coords):
    """Fetch the daily P + ET0 series for many coordinates in ONE call.

    Same contract as `fetch_weather_batch` but for the water-balance series
    (`precipitation_sum` + `et0_fao_evapotranspiration`, 92 past days). The
    series is cached in `weather_cache.json` under the same coordinate key
    (fields `w_daily` / `w_date` / `w_t`) and is only served while
    `w_date == today` — a balance stamped with an earlier calendar day is
    never reused (stale-balance rule), so the index always reflects today.
    """
    cache = _weather_cache_map()
    now = time.time()
    today = date.today().isoformat()
    result = {}
    to_fetch = []

    for lat, lon in coords:
        key = f"{round(lat, 2)},{round(lon, 2)}"
        hit = cache.get(key)
        if (hit and hit.get("w_date") == today
                and (now - hit.get("w_t", 0)) < WATER_TTL):
            result[(lat, lon)] = hit["w_daily"]
        else:
            to_fetch.append((lat, lon, key))

    if not to_fetch:
        return result

    try:
        params = _water_params(
            ",".join(str(lat) for lat, _, _ in to_fetch),
            ",".join(str(lon) for _, lon, _ in to_fetch),
        )
        url = "https://api.open-meteo.com/v1/forecast?" + urllib.parse.urlencode(params)
        req = urllib.request.Request(url, headers={"User-Agent": "BoletsForecast/1.0"})
        with urllib.request.urlopen(req, timeout=20) as r:
            data = json.loads(r.read())
        locations = data if isinstance(data, list) else [data]
        for (lat, lon, key), loc in zip(to_fetch, locations):
            daily = loc.get("daily", {})
            cache.setdefault(key, {}).update({
                "w_t": now, "w_date": today, "w_daily": daily,
            })
            result[(lat, lon)] = daily
        _weather_cache_save()
    except Exception:
        # Degrade: only a *today*-stamped series is reusable; anything older
        # would be a stale balance on a later calendar day.
        for lat, lon, key in to_fetch:
            hit = cache.get(key)
            if hit and hit.get("w_date") == today and hit.get("w_daily"):
                result[(lat, lon)] = hit["w_daily"]
    return result


def _xema_daily_idw(lat, lon, ctx):
    """IDW-interpolated XEMA daily precipitation per calendar day: {day: mm}.

    Extracted from the station selection used by `interpolate_xema` (Phase
    4.2) — nearest ≤ `XEMA_MAX_STATIONS` operative stations within
    `XEMA_RADIUS_KM`, inverse-distance-squared weights — so the water-balance
    blend uses exactly the same neighbours and weighting as the `xema` block.
    Returns {} when there is no XEMA context (no key) or no usable daily data.
    """
    if not ctx:
        return {}
    candidates = []
    for code, meta in (ctx.get("stations") or {}).items():
        try:
            d_km = haversine_m(lat, lon, meta["lat"], meta["lon"]) / 1000.0
        except (TypeError, ValueError, KeyError):
            continue
        if d_km <= XEMA_RADIUS_KM:
            candidates.append((code, meta, d_km))
    candidates.sort(key=lambda t: t[2])
    if not candidates:
        return {}
    used = candidates[:XEMA_MAX_STATIONS]
    by_day = {}
    for code, _meta, _d in used:
        for day, mm in (ctx.get("ppt_day") or {}).get(code, {}).items():
            by_day.setdefault(day, {})[code] = mm
    out = {}
    for day, code_map in by_day.items():
        w_sum = v_sum = 0.0
        for code, _meta, d in used:
            v = code_map.get(code)
            if v is None:
                continue
            w = 1.0 / max(d, 0.5) ** 2
            w_sum += w
            v_sum += w * v
        if w_sum > 0:
            out[day] = v_sum / w_sum
    return out


def blend_water_precip(dates, precip, xema_ctx, lat, lon):
    """Optionally substitute observed XEMA daily mm for modelled P (documented).

    Blend policy (explicit, never silent): for calendar days where Meteocat
    publishes an observed daily accumulation (variable 1300, ≥70 % data
    coverage — enforced when the context is built), the IDW-interpolated
    observed mm replaces the modelled `precipitation_sum` for that day in the
    balance computation. XEMA publishes a day's statistic the following day
    and the context only covers the current month, so only past days can be
    substituted. Returns (blended_series, [blended_date_iso, …]). Without a
    Meteocat key the context is None and nothing is blended.
    """
    if not dates:
        return list(precip), []
    obs = _xema_daily_idw(lat, lon, xema_ctx)
    if not obs:
        return list(precip), []
    today = date.today().isoformat()
    out = list(precip)
    blended = []
    for i, (d, p) in enumerate(zip(dates, precip)):
        v = obs.get(d)
        if d and d < today and v is not None and p is not None:
            out[i] = v
            blended.append(d)
    return out, blended


def compute_water_block(series, xema_ctx=None, lat=None, lon=None):
    """Compute the per-zone `water` block from the daily P + ET0 series.

    Windows end today (the last observed day): `balance_Nd_mm = Σ(P − ET0)`
    over the last N calendar days, summing only days where both values exist
    and recording `days` (the number actually summed). The recharge index is
    the longest usable window (60 → 30 → 14 d, minimum coverage 45/20/7 days)
    normalised by `SOIL_STORAGE_CAP_MM` and clamped to [−1, +1]; the drought
    index is its negative part clamped to [0, 1]; the state label is drought /
    neutral / recharge at ±50 mm (half the cap).

    Returns None when the series has no usable ET0 — the `water` block is
    then absent from the zone payload and the scoring is byte-identical to
    the previous phase (never fabricated).
    """
    if not isinstance(series, dict):
        return None
    time_arr = series.get("time") or []
    precip = series.get("precipitation_sum") or []
    et0 = series.get("et0_fao_evapotranspiration") or []
    n = min(len(time_arr), len(precip), len(et0))
    if n == 0:
        return None
    if all(v is None for v in et0[:n]):
        return None
    today = date.today().isoformat()
    dates = [d for d in time_arr[:n] if isinstance(d, str) and d <= today]
    keep = len(dates)
    if keep == 0:
        return None
    precip = precip[:keep]
    et0 = et0[:keep]
    precip, blend_dates = blend_water_precip(dates, precip, xema_ctx, lat, lon)

    def balance(days):
        total = 0.0
        used = 0
        for pp, ee in zip(precip[-days:], et0[-days:]):
            if pp is not None and ee is not None:
                total += pp - ee
                used += 1
        return (round(total, 1), used) if used else (None, 0)

    windows = {}
    for wd in WATER_WINDOWS_DAYS:
        mm, used = balance(wd)
        windows[f"{wd}d"] = {"mm": mm, "days": used}

    recharge = None
    for wd, min_days in ((60, 45), (30, 20), (14, 7)):
        w = windows[f"{wd}d"]
        if w["mm"] is not None and w["days"] >= min_days:
            recharge = (wd, w["mm"])
            break

    r_idx = d_idx = state = None
    if recharge is not None:
        wd, mm = recharge
        r_idx = round(min(1.0, max(-1.0, mm / SOIL_STORAGE_CAP_MM)), 3)
        d_idx = round(min(1.0, max(0.0, -mm / SOIL_STORAGE_CAP_MM)), 3)
        if mm <= -0.5 * SOIL_STORAGE_CAP_MM:
            state = "drought"
        elif mm >= 0.5 * SOIL_STORAGE_CAP_MM:
            state = "recharge"
        else:
            state = "neutral"

    return {
        "source": ("Open-Meteo: Σ(P − ET0) acumulat per dia; "
                   "P = precipitation_sum, ET0 = et0_fao_evapotranspiration"),
        "computed_at": today,
        "windows": windows,
        "recharge_window": f"{recharge[0]}d" if recharge else None,
        "recharge_index": r_idx,
        "drought_index": d_idx,
        "state": state,
        "storage_cap_mm": SOIL_STORAGE_CAP_MM,
        "blend_days": len(blend_dates),
        "blend_dates": blend_dates,
        "blend_source": ("Meteocat XEMA variable 1300 (IDW, mm)"
                         if blend_dates else None),
    }


def water_modifier(recharge_index, sp):
    """Per-species drought/recharge multiplier for the rain score term.

    Modelling choice, not field-verified (see README): a negative recharge
    index (soil-moisture deficit) damps the rain term — dry soils absorb the
    first rains before fruiting responds — and a positive index boosts it
    slightly. Sensitivity scales with the species' documented
    `rain_trigger_mm` (a species that needs more rain is more sensitive to a
    deficit): k = 0.15 × trigger_mm / 20, m = clamp(1 + k × R, 0.75, 1.25).
    The effect is bounded to ±25 % of the rain term (±~9 % of the weather
    score). Neutral (1.0) when the index is missing.
    """
    if recharge_index is None:
        return 1.0
    k = 0.15 * (float(sp.get("rain_trigger_mm") or 20.0) / 20.0)
    return round(min(1.25, max(0.75, 1.0 + k * float(recharge_index))), 4)

