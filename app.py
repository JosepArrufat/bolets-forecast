# ── Field reports (Phase 5.1) ──────────────────────────────────────────────────
#
# A trip report records what a hunter found (or did not find) so the model can be
# calibrated later (step 5.6). Privacy by design: the client posts a lat/lon, but
# only the 1 km-rounded cell is stored and returned — the exact coordinate is
# never written to disk or exposed, and neither the raw device id nor the client
# IP is stored (both are stored as salted hashes).

REPORTS_DB_FILE = os.environ.get("REPORTS_DB_FILE") or os.path.join(_data_dir, "reports.db")

# Abuse limits (documented ops choices, rolling windows over `created_at`):
REPORTS_MAX_PER_DEVICE_HOUR = 10   # per device hash, rolling 1 h
REPORTS_MAX_PER_DEVICE_DAY  = 50   # per device hash, rolling 24 h
REPORTS_MAX_PER_IP_HOUR     = 60   # per client IP, rolling 1 h (crude global cap)
REPORTS_DEFAULT_DAYS        = 30   # GET default lookback
REPORTS_MAX_DAYS            = 365  # GET hard cap

_reports_lock = threading.Lock()
_reports_ready = False
_device_salt = None


def _reports_init():
    """Create the reports table and indexes once per process."""
    global _reports_ready
    if _reports_ready:
        return
    conn = sqlite3.connect(REPORTS_DB_FILE)
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS reports (
            id             INTEGER PRIMARY KEY AUTOINCREMENT,
            cell_lat       REAL NOT NULL,   -- 1 km-rounded latitude
            cell_lon       REAL NOT NULL,   -- 1 km-rounded longitude
            cell_key       TEXT NOT NULL,   -- "lat,lon" aggregation key
            comarca        TEXT NOT NULL,
            species_id     TEXT,            -- id from mushrooms.json, or NULL
            found          INTEGER NOT NULL, -- 1 = found, 0 = not found
            quantity       INTEGER,         -- specimens (nullable)
            duration_min   INTEGER,         -- time spent (nullable)
            trip_date      TEXT NOT NULL,   -- YYYY-MM-DD the trip happened
            trip_time      TEXT,            -- HH:MM (nullable)
            score_at_time  INTEGER,         -- model score shown at report time (nullable)
            device_hash    TEXT NOT NULL,
            client_ip_hash TEXT NOT NULL,
            created_at     TEXT NOT NULL    -- UTC ISO-8601 submission time
        )
        """
    )
    conn.execute("CREATE INDEX IF NOT EXISTS idx_reports_cell    ON reports(cell_key)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_reports_created ON reports(created_at)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_reports_device  ON reports(device_hash)")
    conn.execute("CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT)")
    conn.commit()
    conn.close()
    _reports_ready = True


def _reports_connect():
    _reports_init()
    return sqlite3.connect(REPORTS_DB_FILE)


def _get_device_salt():
    """A per-deployment random salt so device hashes cannot be trivially reversed."""
    global _device_salt
    if _device_salt is None:
        conn = _reports_connect()
        row = conn.execute("SELECT v FROM meta WHERE k = 'device_salt'").fetchone()
        if row:
            _device_salt = row[0]
        else:
            _device_salt = secrets.token_hex(16)
            conn.execute("INSERT OR REPLACE INTO meta (k, v) VALUES ('device_salt', ?)",
                         (_device_salt,))
            conn.commit()
        conn.close()
    return _device_salt


def round_to_km(lat, lon):
    """Round to 0.01° — ~1.1 km north–south, ~0.8 km east–west at 42°N."""
    return round(lat, 2), round(lon, 2)


def _sha24(value):
    return hashlib.sha256(value.encode("utf-8")).hexdigest()[:24]


def _now_utc():
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _resolve_device_hash(device_id_raw, ip, headers):
    """Salted device hash from an explicit device id or the IP+UA fallback.

    The exact same derivation is used on POST (create) and DELETE (erase), so a
    report can only be deleted by the identity that created it. Never returns or
    stores the raw device id, IP or User-Agent.
    """
    device_id = (device_id_raw or headers.get("X-Device-Id") or "").strip()
    salt = _get_device_salt()
    if device_id:
        return _sha24(device_id + "|" + salt)
    return _sha24(f"{ip}|{headers.get('User-Agent', '')}|" + salt)


def _norm_report(body):
    """Validate and normalize a report body. Raises ValueError with a message."""
    if not isinstance(body, dict):
        raise ValueError("body must be a JSON object")

    try:
        lat = float(body.get("lat"))
        lon = float(body.get("lon"))
    except (TypeError, ValueError):
        raise ValueError("lat and lon are required numbers")
    if not (-90.0 <= lat <= 90.0 and -180.0 <= lon <= 180.0):
        raise ValueError("lat/lon out of range")

    comarca = str(body.get("comarca") or "").strip()
    if not comarca or len(comarca) > 64:
        raise ValueError("comarca is required (max 64 chars)")

    found = body.get("found")
    if isinstance(found, bool):
        found = 1 if found else 0
    elif found in (1, "1"):
        found = 1
    elif found in (0, "0"):
        found = 0
    else:
        raise ValueError("found must be a boolean")

    species_id = body.get("species") or body.get("species_id")
    if species_id is not None:
        species_id = str(species_id).strip() or None
    if species_id is not None and species_id not in {sp.get("id") for sp in SPECIES_LIST}:
        raise ValueError("unknown species id")

    def opt_int(value, name, lo, hi):
        if value is None or value == "":
            return None
        try:
            n = int(value)
        except (TypeError, ValueError):
            raise ValueError(f"{name} must be an integer")
        if not (lo <= n <= hi):
            raise ValueError(f"{name} out of range")
        return n

    quantity = opt_int(body.get("quantity"), "quantity", 0, 10000)
    duration_min = opt_int(body.get("duration_min"), "duration_min", 0, 1440)

    trip_date = body.get("date")
    if trip_date is None or trip_date == "":
        trip_date = date.today().isoformat()
    else:
        try:
            trip_date = datetime.strptime(str(trip_date), "%Y-%m-%d").date().isoformat()
        except ValueError:
            raise ValueError("date must be YYYY-MM-DD")

    trip_time = body.get("time")
    if trip_time is not None:
        trip_time = str(trip_time).strip() or None
        if trip_time is not None and not re.fullmatch(r"[0-2]\d:[0-5]\d", trip_time):
            raise ValueError("time must be HH:MM")

    score_at_time = opt_int(body.get("score"), "score", 0, 99)

    cell_lat, cell_lon = round_to_km(lat, lon)
    cell_key = f"{cell_lat:.2f},{cell_lon:.2f}"

    return {
        "cell_lat": cell_lat, "cell_lon": cell_lon, "cell_key": cell_key,
        "comarca": comarca, "species_id": species_id, "found": found,
        "quantity": quantity, "duration_min": duration_min,
        "trip_date": trip_date, "trip_time": trip_time,
        "score_at_time": score_at_time,
    }


def _rate_limit_hits(conn, device_hash, ip_hash):
    """Return (breach, kind) checking the three rolling limits."""
    now = datetime.now(timezone.utc)

    def count_since(seconds, column, value):
        cutoff = (now - timedelta(seconds=seconds)).strftime("%Y-%m-%dT%H:%M:%SZ")
        return conn.execute(
            f"SELECT COUNT(*) FROM reports WHERE {column} = ? AND created_at > ?",
            (value, cutoff),
        ).fetchone()[0]

    if count_since(3600, "device_hash", device_hash) >= REPORTS_MAX_PER_DEVICE_HOUR:
        return True, "device_hour"
    if count_since(86400, "device_hash", device_hash) >= REPORTS_MAX_PER_DEVICE_DAY:
        return True, "device_day"
    if count_since(3600, "client_ip_hash", ip_hash) >= REPORTS_MAX_PER_IP_HOUR:
        return True, "ip_hour"
    return False, None


def add_report(data, device_hash, ip_hash):
    """Insert a validated report. Returns (id, None) or (None, limit_kind)."""
    with _reports_lock:
        conn = _reports_connect()
        try:
            breach, kind = _rate_limit_hits(conn, device_hash, ip_hash)
            if breach:
                return None, kind
            created_at = _now_utc()
            cur = conn.execute(
                """
                INSERT INTO reports (cell_lat, cell_lon, cell_key, comarca, species_id,
                                     found, quantity, duration_min, trip_date, trip_time,
                                     score_at_time, device_hash, client_ip_hash, created_at)
                VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)
                """,
                (data["cell_lat"], data["cell_lon"], data["cell_key"], data["comarca"],
                 data["species_id"], data["found"], data["quantity"], data["duration_min"],
                 data["trip_date"], data["trip_time"], data["score_at_time"],
                 device_hash, ip_hash, created_at),
            )
            conn.commit()
            return cur.lastrowid, None
        finally:
            conn.close()


def query_reports(bbox=None, days=None):
    """Privacy-safe aggregated counts. bbox = (south, west, north, east)."""
    days = REPORTS_DEFAULT_DAYS if days is None else int(days)
    days = max(1, min(days, REPORTS_MAX_DAYS))
    cutoff = (datetime.now(timezone.utc) - timedelta(days=days)).strftime("%Y-%m-%dT%H:%M:%SZ")

    sql = """
        SELECT cell_lat, cell_lon, comarca, species_id, found, COUNT(*) AS n
        FROM reports
        WHERE created_at > ?
    """
    params = [cutoff]
    if bbox:
        south, west, north, east = bbox
        sql += " AND cell_lat >= ? AND cell_lat <= ? AND cell_lon >= ? AND cell_lon <= ?"
        params += [south, north, west, east]
    sql += " GROUP BY cell_lat, cell_lon, comarca, species_id, found ORDER BY cell_lat, cell_lon"

    conn = _reports_connect()
    try:
        rows = conn.execute(sql, params).fetchall()
        total = conn.execute(
            "SELECT COUNT(*) FROM reports WHERE created_at > ?", [cutoff]
        ).fetchone()[0]
    finally:
        conn.close()

    cells = {}
    for cell_lat, cell_lon, comarca, species_id, found, n in rows:
        key = (cell_lat, cell_lon, comarca)
        cell = cells.setdefault(key, {
            "lat": cell_lat, "lon": cell_lon, "comarca": comarca,
            "found": 0, "not_found": 0, "species": {},
        })
        if found:
            cell["found"] += n
        else:
            cell["not_found"] += n
        if species_id:
            sp = cell["species"].setdefault(species_id, {"found": 0, "not_found": 0})
            if found:
                sp["found"] += n
            else:
                sp["not_found"] += n

    result = sorted(cells.values(), key=lambda c: (c["lat"], c["lon"]))
    return {"reports": result, "total": total, "window_days": days}


def field_report_count():
    """Total stored reports (for the confidence block and later calibration)."""
    conn = _reports_connect()
    try:
        return conn.execute("SELECT COUNT(*) FROM reports").fetchone()[0]
    finally:
        conn.close()


def delete_reports(device_hash, report_id=None):
    """Erase this device's reports (privacy / right-to-deletion path).

    - report_id=None deletes every report whose salted `device_hash` matches.
    - report_id=N deletes only that row, and only if it belongs to the device
      (an id that is unknown or owned by another device is never touched).

    Returns (deleted_count, status) where status ∈ {"ok", "not_found",
    "forbidden"}. No raw identity is ever read back out.
    """
    with _reports_lock:
        conn = _reports_connect()
        try:
            if report_id is not None:
                row = conn.execute(
                    "SELECT device_hash FROM reports WHERE id = ?", (report_id,)
                ).fetchone()
                if row is None:
                    return 0, "not_found"
                if row[0] != device_hash:
                    return 0, "forbidden"
                cur = conn.execute("DELETE FROM reports WHERE id = ?", (report_id,))
                conn.commit()
                return cur.rowcount, "ok"
            cur = conn.execute(
                "DELETE FROM reports WHERE device_hash = ?", (device_hash,)
            )
            conn.commit()
            return cur.rowcount, "ok"
        finally:
            conn.close()


