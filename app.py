def get_zones():
    """Re-read curated zone definitions on each forecast call.

    Zones are keyed by the station name used in `mushrooms.json`. A missing or
    malformed file means "no zones", which keeps the legacy one-station-one-score
    behaviour exactly as it was.
    """
    if not os.path.exists(ZONES_FILE):
        return {}
    try:
        with open(ZONES_FILE) as f:
            data = json.load(f)
    except (ValueError, OSError):
        return {}
    zones = data.get("zones", {}) if isinstance(data, dict) else {}
    return zones if isinstance(zones, dict) else {}


def get_zones_enriched():
    """Re-read the Phase-3 enrichment blocks (DEM/LiDAR/soil/habitat).

    `zones_enriched.json` is generated by `enrich_zones.py` (steps 3.2–3.4) and
    holds one `enrichment` block per zone (terrain, canopy, soil, habitat), each
    with an explicit `source`. It is keyed by station name like `zones.json`, so
    both are merged by station + zone `id` at scoring time.

    A missing/malformed file is not an error: it means "no enrichment", and the
    scoring falls back to the legacy behaviour (no terrain/canopy factors).
    """
    if not os.path.exists(ZONES_ENRICHED_FILE):
        return {}
    try:
        with open(ZONES_ENRICHED_FILE) as f:
            data = json.load(f)
    except (ValueError, OSError):
        return {}
    zones = data.get("zones", {}) if isinstance(data, dict) else {}
    return zones if isinstance(zones, dict) else {}


def _enrichment_lookup():
    """Return {zone_id: enrichment_block} across all stations, built lazily."""
    lookup = {}
    for _station, zones in get_zones_enriched().items():
        if not isinstance(zones, list):
            continue
        for zone in zones:
            zid = zone.get("id")
            if zid and isinstance(zone.get("enrichment"), dict):
                lookup[zid] = zone["enrichment"]
    return lookup

