def compute_zone_confidence(zone, enrichment, geo, xema_block, water_block,
                            water_fetched):
    """The per-zone `confidence` block (Phase 4.4). Reporting-only.

    Two distinct concepts, per the step spec:

    - `completeness_pct`: fraction of the inputs the zone's score actually
      uses that are present with real data (weather, xema, water, terrain,
      canopy, soil, habitat, curated). XEMA is counted only when a Meteocat
      key is configured (its pipeline is active) and the water balance only
      when the water series was actually fetched, so a keyless run scores
      completeness *without* those inputs — never zero.
    - `score` / `level`: deterministic prediction confidence from sourced
      reasons (nearest-station distance + data age, Open-Meteo grid
      coarseness, DEM/LiDAR/soil/habitat source resolutions, the curated
      zone confidence, and the honest field-report count of zero). It is
      displayed, never multiplied into any score.
    """
    enrich = enrichment or {}
    comp_inputs = {
        "weather": True,  # a zone is only scored when weather exists
        "terrain": bool((enrich.get("terrain") or {}).get("source")
                        or (enrich.get("terrain") or {}).get("dem_aspect_deg") is not None),
        "canopy": bool((enrich.get("canopy") or {}).get("status") == "complete"
                       and (enrich.get("canopy") or {}).get("canopy_pct") is not None),
        "soil": bool((enrich.get("soil") or {}).get("status") == "complete"
                     and (enrich.get("soil") or {}).get("type")),
        "habitat": bool((enrich.get("habitat") or {}).get("status") == "complete"),
        "curated": isinstance(zone.get("confidence"), (int, float)),
    }
    if METEOCAT_API_KEY:
        comp_inputs["xema"] = xema_block is not None
    if water_fetched:
        comp_inputs["water"] = water_block is not None
    present = sum(1 for v in comp_inputs.values() if v)
    completeness_pct = round(100 * present / len(comp_inputs))

    q = _conf_quality(zone, enrich, geo, xema_block)
    wsum = qsum = 0.0
    for inp, w in CONF_WEIGHTS.items():
        qv = q.get(inp)
        if qv is None:
            continue   # xema absent → its weight redistributes (documented)
        wsum += w
        qsum += w * qv
    score = round(qsum / wsum, 3) if wsum else None
    level = next((lbl for th, lbl in CONF_LEVEL_THRESHOLDS
                  if score is not None and score >= th), "baixa")

    return {
        "computed_at": date.today().isoformat(),
        "completeness_pct": completeness_pct,
        "completeness": comp_inputs,
        "level": level,
        "score": score,
        "field_reports": FIELD_REPORTS_COUNT,
        "reasons": _conf_reasons(zone, enrich, xema_block, water_block,
                                 water_fetched, q),
    }


def _species_wants_open_canopy(sp):
    """Same documented condition as `canopy_openness_factor` (species notes)."""
    notes = (sp.get("notes") or "").lower()
    return ("open" in notes or "sense sotabosc" in notes
            or "no undergrowth" in notes
            or ("sense" in notes and "sotabosc" in notes))


def compute_species_confidence(sp_def, geo, enrichment, water_block, q):
    """Per-species confidence (Phase 4.4), deterministic and reporting-only.

    Uses only the inputs the species' *active* scoring factors depend on,
    derived from its documented preferences in mushrooms.json:

    - soil    → the species documents a soil-pH preference
    - forest  → the species documents tree associations
    - canopy  → the species notes mention open / no-undergrowth habitat and
                LiDAR canopy data is present
    - terrain → the species has an aspect preference, or is frost-sensitive
                (temp_min > 2 °C, the documented cold-air gating)
    - xema    → the water balance blended observed XEMA rain (a rain-term input)
    - weather, curation, reports → always

    Returns {"score", "label", "inputs", "field_reports"}.
    """
    terr = (enrichment or {}).get("terrain") or {}
    can  = (enrichment or {}).get("canopy") or {}
    slope_aspect = sp_def.get("slope_aspect") or []
    has_aspect_pref = bool(slope_aspect) and "any" not in slope_aspect
    t_min = (sp_def.get("temperature_c") or {}).get("min")
    frost_sensitive = isinstance(t_min, (int, float)) and t_min > 2.0
    active = {
        "weather":  True,
        "xema":     bool(water_block and water_block.get("blend_days")),
        "terrain":  has_aspect_pref or frost_sensitive,
        "canopy":   _species_wants_open_canopy(sp_def)
                    and can.get("canopy_pct") is not None,
        "soil":     bool((sp_def.get("soil") or {}).get("ph")),
        "forest":   bool(sp_def.get("tree_keywords")),
        "curation": True,
        "reports":  True,
    }
    wsum = qsum = 0.0
    inputs = []
    for inp, w in CONF_WEIGHTS.items():
        if not active.get(inp):
            continue
        qv = q.get(inp)
        if qv is None:      # xema active requires a blend → block present
            continue
        wsum += w
        qsum += w * qv
        inputs.append(inp)
    score = round(qsum / wsum, 3) if wsum else None
    level = next((lbl for th, lbl in CONF_LEVEL_THRESHOLDS
                  if score is not None and score >= th), "baixa")
    return {"score": score, "label": level, "inputs": inputs,
            "field_reports": FIELD_REPORTS_COUNT}

# ── Place search (geocoding proxy) ────────────────────────────────────────────

def geocode_place(query):
    """Forward a place search to Nominatim with a proper User-Agent.

    Kept server-side so the browser never has to deal with CORS or rate-limit
    headers, and so we can restrict results to the Pyrenees / Catalonia box.
    """
    q = (query or "").strip()
    if len(q) < 2:
        return []
    params = {
        "q": q,
        "format": "jsonv2",
        "limit": 6,
        "accept-language": "ca,es,en",
        "countrycodes": "es,ad,fr",
        # Soft bias to Catalonia; viewbox is left,top,right,bottom
        "viewbox": "-0.5,43.2,3.5,40.4",
        "bounded": 0,
    }
    url = "https://nominatim.openstreetmap.org/search?" + urllib.parse.urlencode(params)
    req = urllib.request.Request(
        url,
        headers={
            "User-Agent": "BoletsForecast/1.0 (mushroom forecast; contact: local)",
            "Accept-Language": "ca,es,en",
        },
    )
    with urllib.request.urlopen(req, timeout=12) as r:
        rows = json.loads(r.read())
    out = []
    for row in rows:
        try:
            out.append({
                "name": row.get("display_name", "").split(",")[0],
                "display": row.get("display_name", ""),
                "lat": float(row["lat"]),
                "lon": float(row["lon"]),
                "type": row.get("type", ""),
                "category": row.get("category", ""),
            })
        except (KeyError, TypeError, ValueError):
            continue
    return out

# ── Nearby parking (OpenStreetMap / Overpass, proxied server-side) ────────────

def haversine_m(lat1, lon1, lat2, lon2):
    R = 6371000
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp = math.radians(lat2 - lat1)
    dl = math.radians(lon2 - lon1)
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * R * math.asin(math.sqrt(h))

def find_parking(lat, lon, radius_m=2500):
    """Return the nearest mapped parking places around a zone.

    Results are precomputed in `parking_cache.json` for the known stations.
    Unknown points fall back to a live Overpass query. Overpass rejects requests
    without a descriptive User-Agent (HTTP 406), so this stays server-side.
    """
    key = f"{lat:.4f},{lon:.4f}"
    with _parking_lock:
        cached = PARKING_CACHE.get(key)
    if cached is not None:
        return cached

    query = (
        f'[out:json][timeout:20];'
        f'(node["amenity"="parking"](around:{int(radius_m)},{lat},{lon});'
        f'way["amenity"="parking"](around:{int(radius_m)},{lat},{lon}););'
        f'out center 12;'
    )
    body = urllib.parse.urlencode({"data": query}).encode()

    data = None
    last_err = None
    for endpoint in ("https://overpass-api.de/api/interpreter",):
        try:
            req = urllib.request.Request(
                endpoint,
                data=body,
                headers={
                    "User-Agent": "BoletsForecast/1.0 (mushroom forecast; local app)",
                    "Content-Type": "application/x-www-form-urlencoded",
                },
            )
            with urllib.request.urlopen(req, timeout=12) as r:
                data = json.loads(r.read())
            break
        except Exception as e:
            last_err = e
    if data is None:
        raise last_err or RuntimeError("Overpass unavailable")

    rows = []
    for el in data.get("elements", []):
        center = el.get("center") or {}
        plat = el.get("lat", center.get("lat"))
        plon = el.get("lon", center.get("lon"))
        if plat is None or plon is None:
            continue
        tags = el.get("tags") or {}
        rows.append({
            "name": tags.get("name") or "Aparcament",
            "lat": plat,
            "lon": plon,
            "distance_m": round(haversine_m(lat, lon, plat, plon)),
            "capacity": tags.get("capacity"),
        })
    rows.sort(key=lambda x: x["distance_m"])
    rows = rows[:5]

    with _parking_lock:
        PARKING_CACHE[key] = rows
        try:
            save_parking_cache(PARKING_CACHE)
        except OSError:
            pass
    return rows

# ── Data quality (not prediction confidence) ───────────────────────────────────

def data_quality(weather, geo):
    """How complete are the inputs behind a station's score?

    This is deliberately *data completeness*, not a probability. It tells the
    user whether the score rests on full weather + soil + forest data or on
    fallbacks. Naming it "qualitat de dades" avoids pretending it is a
    calibrated confidence interval.
    """
    pct = 0
    reasons = []

    precip = [p for p in (weather or {}).get("precipitation_sum", []) if p is not None]
    temps  = [t for t in (weather or {}).get("temperature_2m_max", []) if t is not None]
    if len(precip) >= 7 and len(temps) >= 5:
        pct += 40
    else:
        reasons.append("meteo incompleta")

    soil = (geo or {}).get("soil_type")
    if soil in ("calcareous", "siliceous", "mixed"):
        pct += 30
    else:
        reasons.append("sòl desconegut")

    forest = (geo or {}).get("forest_code")
    if forest and forest != "unknown":
        pct += 30
    else:
        reasons.append("bosc desconegut")

    if pct >= 90:
        label = "alta"
    elif pct >= 60:
        label = "mitjana"
    else:
        label = "baixa"

    return {"pct": pct, "label": label, "reasons": reasons}

# ── Scoring helpers ───────────────────────────────────────────────────────────

def gaussian_score(value, ideal_min, ideal_max, hard_min=None, hard_max=None):
    if hard_min is not None and value < hard_min: return 0.0
    if hard_max is not None and value > hard_max: return 0.0
    if ideal_min <= value <= ideal_max: return 1.0
    center = (ideal_min + ideal_max) / 2
    sigma  = (ideal_max - ideal_min) / 2
    return math.exp(-0.5 * ((value - center) / (sigma + 1e-9)) ** 2)

def rain_score(precip, trigger_mm, window_days, dry_spell_before):
    if len(precip) < window_days:
        window_days = len(precip)
    recent = precip[-window_days:]
    total  = sum(p for p in recent if p is not None)
    base   = min(total / max(trigger_mm, 1), 1.5)
    # Dry spell bonus
    if dry_spell_before > 0 and len(precip) >= window_days + dry_spell_before:
        pre = precip[-(window_days + dry_spell_before):-window_days]
        pre_total = sum(p for p in pre if p is not None)
        if pre_total < 5:
            base = min(base * 1.2, 1.5)
    return min(base, 1.0)

def wind_score(gusts, sensitivity):
    recent = [g for g in gusts[-3:] if g is not None]
    if not recent: return 0.5
    avg = sum(recent) / len(recent)
    threshold = {"high": 25, "medium": 35, "low": 50}.get(sensitivity, 35)
    return max(0.0, 1.0 - avg / threshold)

def temp_score(t_max, t_min, sp):
    recent_max = [t for t in t_max[-5:] if t is not None]
    recent_min = [t for t in t_min[-5:] if t is not None]
    if not recent_max or not recent_min: return 0.5
    avg = (sum(recent_max)/len(recent_max) + sum(recent_min)/len(recent_min)) / 2
    t = sp["temperature_c"]
    return gaussian_score(avg, t["ideal_min"], t["ideal_max"],
                          hard_min=t["min"], hard_max=t["max"])

def humidity_score(humidity):
    recent = [h for h in humidity[-5:] if h is not None]
    if not recent: return 0.5
    return min(sum(recent) / len(recent) / 70.0, 1.0)

# ── Terrain & microclimate factors (Phase 3.5) ────────────────────────────────
#
# These turn the Phase-3 enrichment blocks (aspect, solar radiation, cold-air
# pooling, canopy/undergrowth) into per-species multipliers. Every value is a
# deterministic function of the species preferences in `mushrooms.json` and the
# sampled enrichment data; nothing here invents a preference. When a zone has no
# enrichment block (or a factor's data is missing), the factor is neutral (1.0),
# so the legacy score is preserved exactly.

ASPECT_TO_DEG = {
    "north": 0.0, "northeast": 45.0, "east": 90.0, "southeast": 135.0,
    "south": 180.0, "southwest": 225.0, "west": 270.0, "northwest": 315.0,
}

def _angular_diff(a, b):
    d = abs((a - b) % 360.0)
    return min(d, 360.0 - d)

def aspect_match_factor(slope_aspect, aspect_deg):
    """How well a zone's aspect matches the species' preferred slope aspect.

    `slope_aspect` is the species list from mushrooms.json (e.g. ["north",
    "northeast"] or ["any"]); `aspect_deg` is the zone's downslope direction
    (0–360°, clockwise from north). Returns (factor, label) where the factor is
    1.0 for a match, gently penalised for a mismatch, and the label describes the
    match in human terms.
    """
    if not slope_aspect or "any" in slope_aspect or aspect_deg is None:
        return 1.0, "neutral"
    preferred = [ASPECT_TO_DEG[d] for d in slope_aspect if d in ASPECT_TO_DEG]
    if not preferred:
        return 1.0, "neutral"
    best = min(_angular_diff(aspect_deg, p) for p in preferred)
    if best <= 45.0:
        return 1.0, "match"
    if best >= 135.0:
        return 0.85, "opposite"
    return 0.93, "partial"


def solar_match_factor(slope_aspect, solar_ratio):
    """Match potential clear-sky insolation to the species' aspect preference.

    `solar_ratio` is the enrichment `solar_radiation` (tilted/horizontal,
    annual). Species that prefer south-facing slopes (solana) do best with more
    potential insolation; north-facing (obaga) species with less. The factor is
    kept close to 1.0 (±0.1) because solar radiation is a secondary driver
    behind the aspect match itself.
    """
    if not slope_aspect or "any" in slope_aspect or solar_ratio is None:
        return 1.0, "neutral"
    south_like = any(d in slope_aspect for d in ("south", "southeast", "southwest"))
    north_like = any(d in slope_aspect for d in ("north", "northeast", "northwest"))
    # Clamp the ratio around a neutral ~1.0; the enrichment values span ~0.75–1.5.
    x = min(max((solar_ratio - 1.0) / 0.5, -1.0), 1.0)  # -1 … +1
    if south_like and not north_like:
        return round(1.0 + 0.10 * x, 3), "south"
    if north_like and not south_like:
        return round(1.0 - 0.10 * x, 3), "north"
    return 1.0, "neutral"


def cold_air_factor(pooling, temp_min):
    """Cold-air pooling penalty, gated by the species' cold tolerance.

    `pooling` is the enrichment `cold_air_pooling` (m): ~0 means the zone sits in
    a local depression where cold air settles, a large positive value means it
    drains. Frost-sensitive species (high `temp_min`) are penalised in pooling
    zones; very cold-tolerant species are barely affected. This is a gentle
    effect (±5%) and neutral when the data is missing.
    """
    if pooling is None or temp_min is None:
        return 1.0, "neutral"
    frostiness = min(max((temp_min - 2.0) / 8.0, 0.0), 1.0)  # 0 (tolerant) … 1 (sensitive)
    if pooling <= 10.0:
        # Sits in a cold depression → penalise frost-sensitive species.
        return round(1.0 - 0.05 * frostiness, 3), "pooling"
    if pooling >= 50.0:
        # Drains well → small bonus for frost-sensitive species.
        return round(1.0 + 0.03 * frostiness, 3), "drained"
    return 1.0, "neutral"


def canopy_openness_factor(sp, canopy_pct, undergrowth):
    """Reward/penalise canopy openness where a species' notes mention it.

    The species notes are the only authoritative source for canopy preference.
    When the notes mention an open / no-undergrowth habitat (e.g. rovelló,
    fredolic) and the LiDAR shows a closed canopy with shrub undergrowth, apply a
    mild penalty; an open canopy is rewarded. Species without such a note are
    neutral, so this never invents a preference.
    """
    notes = (sp.get("notes") or "").lower()
    wants_open = ("open" in notes or "sense sotabosc" in notes or "no undergrowth" in notes
                  or "sense" in notes and "sotabosc" in notes)
    if not wants_open or canopy_pct is None:
        return 1.0, "neutral"
    dense = canopy_pct >= 0.7 and (undergrowth or 0.0) >= 0.2
    if dense:
        return 0.95, "closed"
    if canopy_pct <= 0.5:
        return 1.03, "open"
    return 1.0, "neutral"


def phenology_factor(sp, month):
    """Simple season gate for the `P` factor (phenology).

    Phase 4.5 replaced the zone `P` with a GDD-based state (see
    `species_phenology`); this month gate is now used two ways:
    - stations: unchanged since Phase 2 (byte-identical payloads), and
    - zones: as the calendar multiplier on top of the GDD-based factor,
      so out-of-season months stay damped (spring species score 1.0 in
      spring — they are filtered out otherwise — autumn species 1.0 in
      the autumn peak Sep–Nov, a slight reduction in Aug/Dec and a clear
      reduction outside the season).
    """
    if sp.get("season") == "spring":
        return 1.0 if month in (3, 4, 5) else 0.0
    if month in (9, 10, 11):
        return 1.0
    if month in (8, 12):
        return 0.85
    return 0.5

# ── Phenology: growing-degree days + altitude lag (Phase 4.5) ─────────────────
#
# GDD (suma tèrmica) = Σ max(0, T_mean − T_base) over a 14-day rolling window.
# Inputs are the real, already-fetched daily temperature series (Open-Meteo,
# past_days=14 + 7 forecast days — no extra network call) lapse-corrected to
# the zone's curated altitude with the documented 6.5 °C/km constant.
#
# Per species, T_base is the documented hard minimum `temperature_c.min` from
# mushrooms.json — the species cannot grow below it, so heat above it is what
# accumulates. The window open/close thresholds are pure arithmetic on the
# documented band:
#   gdd_open  = 14 × (ideal_min − base)
#   gdd_close = 14 × (ideal_max − base)
# A rolling sum (not a since-September total) is used deliberately: it can
# both open AND close, so the "rovelló wave" moves up in altitude as the
# season advances and the crest passes each altitude band. Modelling choices
# (documented in README "Phenology and altitude lag"):
#   - 14-day window: the length of the stored temperature series.
#   - state "opening" starts at 0.5 × gdd_open (half the opening heat).
#   - at least 7 valid days needed for a trustworthy sum.
#   - P ramps linearly 0.5 → 1.0 between closed and open, and 1.0 → 0.5
#     beyond gdd_close (heat above the documented band).
# The month gate above multiplies the GDD factor (P = P_gdd × gate).

PHENO_WINDOW_DAYS = 14        # matches the stored series (past_days=14)
PHENO_OPEN_FRACTION = 0.5     # "opening" starts at half the opening GDD
PHENO_MIN_DAYS_USED = 7       # ≥ 7 valid days in the window, else nulls
PHENO_LAG_MIN_GDD = 2.8       # ≥ ~0.2 °C·d/day heat rate, else lag = null
PHENO_LAG_MAX_DAYS = 30.0     # lag beyond a month is meaningless → null


def _gdd_window(t_max, t_min, end_idx, base_c):
    """Rolling GDD over `PHENO_WINDOW_DAYS` days ending at `end_idx` (inclusive).

    Returns (gdd, days_used); gdd is None when fewer than
    `PHENO_MIN_DAYS_USED` days carry both temperatures (nothing fabricated).
    """
    vals = []
    start = end_idx - PHENO_WINDOW_DAYS + 1
    for i in range(start, end_idx + 1):
        if i < 0 or i >= len(t_max) or i >= len(t_min):
            continue
        hi, lo = t_max[i], t_min[i]
        if hi is None or lo is None:
            continue
        vals.append(max(0.0, (hi + lo) / 2.0 - base_c))
    if len(vals) < PHENO_MIN_DAYS_USED:
        return None, len(vals)
    return round(sum(vals), 1), len(vals)


def pheno_state(gdd, gdd_open, gdd_close):
    if gdd is None:
        return None
    if gdd < PHENO_OPEN_FRACTION * gdd_open:
        return "closed"
    if gdd < gdd_open:
        return "opening"
    if gdd <= gdd_close:
        return "open"
    return "closing"


def pheno_p_factor(gdd, gdd_open, gdd_close, gate):
    """Deterministic P from GDD vs the documented band × the calendar gate."""
    if gdd is None:
        return round(gate, 3) if gate is not None else None
    if gdd < gdd_open:
        p_gdd = 0.5 + 0.5 * (gdd / gdd_open)
    elif gdd <= gdd_close:
        p_gdd = 1.0
    else:
        p_gdd = max(0.5, 1.0 - 0.5 * (gdd - gdd_close) / gdd_close)
    return round(p_gdd * gate, 3)


def species_phenology(sp, daily, end_idx, month):
    """GDD-based phenology block for one species and one `end_idx` day offset.

    `daily` is the zone's lapse-corrected Open-Meteo daily payload (14 past +
    7 forecast days). `end_idx` is the index of the day the state describes
    (today for offset 0). Returns a dict with explicit nulls when the
    temperature series is missing or too short — never fabricated values.
    """
    t_max = daily.get("temperature_2m_max") or []
    t_min = daily.get("temperature_2m_min") or []
    base_c = sp["temperature_c"].get("min")
    if base_c is None:
        base_c = 0.0
    ideal = sp["temperature_c"]
    gdd_open = round(PHENO_WINDOW_DAYS
                     * max(0.0, ideal["ideal_min"] - base_c), 1)
    gdd_close = round(PHENO_WINDOW_DAYS
                      * max(0.0, ideal["ideal_max"] - base_c), 1)

    gdds, states = [], []
    for o in range(7):
        e = min(end_idx + o, len(t_max) - 1, len(t_min) - 1)
        g, _n = _gdd_window(t_max, t_min, e, base_c)
        gdds.append(g)
        states.append(pheno_state(g, gdd_open, gdd_close))
    gdd0, n0 = gdds[0], None
    _, n0 = _gdd_window(t_max, t_min, end_idx, base_c)

    days_to_open = None
    if states[0] == "open":
        days_to_open = 0
    else:
        for o, st in enumerate(states):
            if st == "open":
                days_to_open = o
                break
        if days_to_open is None:
            for o, st in enumerate(states):
                if st == "opening":
                    days_to_open = o
                    break
    days_to_close = None
    if states[0] in ("opening", "open"):
        for o, st in enumerate(states):
            if st == "closed":
                days_to_close = o
                break

    gate = phenology_factor(sp, month)
    return {
        "gdd_base_c":       base_c,
        "gdd_now":          gdd0,
        "gdd_open":         gdd_open,
        "gdd_close":        gdd_close,
        "state":            states[0],
        "p_factor":         pheno_p_factor(gdd0, gdd_open, gdd_close, gate),
        "days_to_open":     days_to_open,
        "days_to_close":    days_to_close,
        "window_days":      PHENO_WINDOW_DAYS,
        "days_used":        n0,
        "gdd_forecast":     gdds,
        "altitude_lag_days": None,   # filled by _apply_altitude_lag
    }


# ── Soil & forest multipliers ─────────────────────────────────────────────────

def soil_multiplier(sp, soil_type):
    """How well does this soil type match the species preference?"""
    pref = sp["soil"]["ph"]  # "basic", "acid", "neutral_to_acid", etc.
    if soil_type == "unknown":
        return 0.9  # slight penalty for missing data
    if soil_type == "mixed":
        return 0.85
    is_acid = "acid" in pref
    is_basic = "basic" in pref and "acid" not in pref
    is_neutral = "neutral" in pref and "acid" not in pref and "basic" not in pref
    if soil_type == "calcareous":
        if is_acid:   return 0.15  # strong mismatch
        if is_basic:  return 1.0
        return 0.75  # neutral tolerance
    if soil_type == "siliceous":
        if is_acid:   return 1.0
        if is_basic:  return 0.15  # strong mismatch
        return 0.75
    return 1.0

def forest_multiplier(sp, forest_code):
    """How well does the detected forest type match the species' trees?"""
    if forest_code == "unknown":
        return 0.9
    if forest_code not in FOREST_CODES:
        # Not a forest at all (urban, pasture, etc.)
        pref_trees = sp.get("tree_keywords", [])
        if any(k in ["grassland", "meadow", "prat", "herba", "forest edge"]
               for k in pref_trees):
            return 1.0  # species likes open/meadow habitat
        return 0.3
    # 311=broadleaf, 312=conifer, 313=mixed, 324=transitional
    pref_trees = sp.get("tree_keywords", [])
    needs_pine = sp.get("prefers_scots_pine", False)
    needs_broadleaf = any(k in ["faig", "roure", "castanyer", "beech", "oak", "chestnut"]
                          for k in pref_trees)
    if forest_code == "312":  # conifer
        if needs_pine: return 1.0
        if needs_broadleaf: return 0.3
        return 0.8
    if forest_code == "311":  # broadleaf
        if needs_broadleaf: return 1.0
        if needs_pine: return 0.2
        return 0.7
    if forest_code == "313":  # mixed
        return 0.85
    if forest_code == "324":  # transitional
        return 0.6
    return 0.8

# ── Main scoring function ─────────────────────────────────────────────────────

def score_station(station, weather, geo, day_offset=0, water=None, phenology=None):
    """Score all species for a station.
    day_offset=0 → today, 1 → tomorrow, … 6 → 6 days from now.
    The weather arrays have past_days=14 + forecast_days=7, total ~21 entries.
    day_offset shifts which 'current' day we treat as 'now'.

    Phase 4.3: `water` is the zone's soil-water-balance block (absent for
    stations, which keeps their payload byte-identical). When present, the
    rain score term is scaled by the documented drought/recharge modifier
    (`water_modifier`); the raw rain score stays visible in
    `breakdown.pluja` and the modifier appears as `breakdown.sequera` (percent,
    100 = neutral) only on zone species.

    Phase 4.5: `phenology` is the zone's lapse-corrected daily payload (zones
    only; None for stations, whose payload and score stay byte-identical).
    When present, each species result carries a GDD-based `phenology` block
    and the `P` factor comes from it (multiplied into the zone score); the
    station path keeps the Phase-2 month gate and is untouched.
    """
    # Total array length: past(14) + today(1) + future(6) = 21
    # Index of 'today' in the array = len - 7 (last 7 are forecast)
    total_len = len(weather["precipitation_sum"])
    # today_idx is the index after which data is forecast
    today_idx = total_len - 7  # e.g. 14

    # Shift: for day_offset=N we pretend we're N days in the future
    # so the 'past' window ends at today_idx + day_offset
    end = today_idx + day_offset  # exclusive end of 'past' data

    precip   = weather["precipitation_sum"][:end + 1]
    t_max    = weather["temperature_2m_max"][:end + 1]
    t_min    = weather["temperature_2m_min"][:end + 1]
    wind     = weather["windspeed_10m_max"][:end + 1]
    humidity = weather["relative_humidity_2m_max"][:end + 1]

    results = []
    current_month = date.today().month

    for sp in SPECIES_LIST:
        if sp.get("season") == "spring" and current_month not in (3, 4, 5):
            continue

        r_sc_raw = rain_score(precip, sp["rain_trigger_mm"],
                              sp["rain_window_days"], sp["dry_spell_before_days"])
        # Phase 4.3: drought/recharge modifier on the rain term (zones only).
        r_sc = r_sc_raw
        water_m = None
        if water is not None and water.get("recharge_index") is not None:
            water_m = water_modifier(water["recharge_index"], sp)
            r_sc = min(1.0, r_sc_raw * water_m)
        t_sc = temp_score(t_max, t_min, sp)
        w_sc = wind_score(wind, sp["wind_sensitivity"])
        h_sc = humidity_score(humidity)
        alt  = station.get("alt_m", 900)
        a    = sp["altitude_m"]
        a_sc = gaussian_score(alt, a["ideal_min"], a["ideal_max"],
                              hard_min=a["min"], hard_max=a["max"])

        base   = (r_sc * 0.35 + t_sc * 0.25 + w_sc * 0.20 +
                  a_sc * 0.10 + h_sc * 0.10)
        s_mult = soil_multiplier(sp, geo["soil_type"])
        f_mult = forest_multiplier(sp, geo["forest_code"])

        # ── Phase 3.5 terrain/canopy factors (neutral when no enrichment) ──
        enrichment  = station.get("_enrichment") or {}
        terrain     = enrichment.get("terrain") or {}
        canopy      = enrichment.get("canopy") or {}
        aspect_deg  = terrain.get("dem_aspect_deg", terrain.get("aspect_deg"))
        solar_ratio = (terrain.get("solar_radiation") or {}).get("annual")
        pooling     = terrain.get("cold_air_pooling")
        canopy_pct  = canopy.get("canopy_pct")
        undergrowth = canopy.get("undergrowth")

        a_match, a_match_label = aspect_match_factor(sp.get("slope_aspect"), aspect_deg)
        s_match, s_match_label = solar_match_factor(sp.get("slope_aspect"), solar_ratio)
        c_match, c_match_label = cold_air_factor(pooling, sp["temperature_c"].get("min"))
        open_f, open_label     = canopy_openness_factor(sp, canopy_pct, undergrowth)
        # Phase 4.5: zones get a GDD-based P; stations keep the month gate.
        ph = None
        if phenology is not None:
            ph = species_phenology(sp, phenology, end, current_month)
            p_factor = ph["p_factor"]
            if p_factor is None:
                p_factor = phenology_factor(sp, current_month)
        else:
            p_factor = phenology_factor(sp, current_month)

        micro_factor    = a_match * s_match * c_match   # M — microclimate
        habitat_factor  = s_mult * f_mult * open_f      # H — habitat (soil × forest × canopy)
        total           = base * habitat_factor * micro_factor
        if phenology is not None:
            # Phase 4.5: P (phenology) now enters the ZONE score only.
            total *= p_factor

        pct = round(min(total * 100, 99))
        if pct >= 75:   label = "Molt bona"
        elif pct >= 55: label = "Bona"
        elif pct >= 35: label = "Possible"
        else:           label = "Baixa"

        # Raw numbers for educational explanation
        p7  = round(sum(p for p in precip[-7:] if p is not None), 1)
        p14 = round(sum(p for p in precip[-14:] if p is not None), 1)
        pre_window = precip[-(sp["rain_window_days"]+sp["dry_spell_before_days"]):-sp["rain_window_days"]] \
            if len(precip) >= sp["rain_window_days"]+sp["dry_spell_before_days"] else []
        pre_dry = sum(1 for p in pre_window if p is not None and p < 1)

        recent_max_vals = [t for t in t_max[-5:] if t is not None]
        recent_min_vals = [t for t in t_min[-5:] if t is not None]
        avg_max = round(sum(recent_max_vals)/len(recent_max_vals), 1) if recent_max_vals else None
        avg_min = round(sum(recent_min_vals)/len(recent_min_vals), 1) if recent_min_vals else None
        t_avg   = round((avg_max + avg_min)/2, 1) if avg_max and avg_min else None

        recent_gusts = [g for g in wind[-3:] if g is not None]
        w3     = round(max(recent_gusts, default=0))
        w3_avg = round(sum(recent_gusts)/len(recent_gusts), 1) if recent_gusts else 0

        recent_hum = [h for h in humidity[-5:] if h is not None]
        avg_hum = round(sum(recent_hum)/len(recent_hum), 1) if recent_hum else None

        wind_thresh = {"high": 25, "medium": 35, "low": 50}.get(sp["wind_sensitivity"], 35)

        breakdown = {
            "pluja":       round(r_sc_raw * 100),
            "temperatura": round(t_sc * 100),
            "vent":        round(w_sc * 100),
            "altitud":     round(a_sc * 100),
            "humitat":     round(h_sc * 100),
        }
        if water_m is not None:
            # Phase 4.3: 100 = neutral, <100 drought-damped, >100 recharge-boosted.
            breakdown["sequera"] = round(water_m * 100)

        r = {
            "id":         sp["id"],
            "name":       sp["common_name"],
            "scientific": sp["scientific_name"],
            "score":      pct,
            "label":      label,
            "soil_match":   round(s_mult * 100),
            "forest_match": round(f_mult * 100),
            "factors": {
                "H": {"score": round(habitat_factor * 100),
                      "soil": round(s_mult * 100),
                      "forest": round(f_mult * 100),
                      "canopy": round(open_f * 100)},
                "M": {"score": round(micro_factor * 100),
                      "aspect": round(a_match * 100),
                      "aspect_label": a_match_label,
                      "solar": round(s_match * 100),
                      "solar_label": s_match_label,
                      "cold_air": round(c_match * 100),
                      "cold_air_label": c_match_label},
                "W": round(base * 100),
                "P": round(p_factor * 100),
                "C": {"confidence": station.get("_confidence"),
                      "label": station.get("_confidence_label")},
            },
            "terrain": {
                "aspect_deg": aspect_deg,
                "solar_ratio": solar_ratio,
                "cold_air_pooling": pooling,
                "canopy_pct": canopy_pct,
                "undergrowth": undergrowth,
            } if enrichment else None,
            "breakdown": breakdown,
            "weather": {
                "rain_7d":  p7,
                "rain_14d": p14,
                "temp_avg": t_avg,
                "avg_max":  avg_max,
                "avg_min":  avg_min,
                "wind_max": w3,
                "wind_avg": w3_avg,
                "humidity": avg_hum,
                "pre_dry_days": pre_dry,
            },
            # species thresholds — sent to frontend for explanation
            "thresholds": {
                "rain_trigger_mm":      sp["rain_trigger_mm"],
                "rain_window_days":     sp["rain_window_days"],
                "dry_spell_before_days":sp["dry_spell_before_days"],
                "temp_ideal_min":       sp["temperature_c"]["ideal_min"],
                "temp_ideal_max":       sp["temperature_c"]["ideal_max"],
                "temp_min":             sp["temperature_c"]["min"],
                "temp_max":             sp["temperature_c"]["max"],
                "wind_sensitivity":     sp["wind_sensitivity"],
                "wind_threshold_kmh":   wind_thresh,
                "alt_ideal_min":        sp["altitude_m"]["ideal_min"],
                "alt_ideal_max":        sp["altitude_m"]["ideal_max"],
                "soil_ph":              sp["soil"]["ph"],
                "tree_keywords":        sp["tree_keywords"][:4],
                "prefers_scots_pine":   sp.get("prefers_scots_pine", False),
            },
            "soil_type":    geo["soil_type"],
            "litho_text":   geo["litho_text"],
            "forest_code":  geo["forest_code"],
            "forest_label": geo["forest_label"],
            "ph":           geo.get("ph"),
            "notes":        sp["notes"],
        }
        if ph is not None:
            # Phase 4.5: GDD phenology block (zone species only — explicit
            # nulls when the temperature series is unusable, never fabricated).
            r["phenology"] = ph
        results.append(r)

    results.sort(key=lambda x: x["score"], reverse=True)
    return results

# ── Per-zone scoring ──────────────────────────────────────────────────────────

def zone_score_summary(days, dates):
    """Best species, best score and best day across the 7-day window."""
    best = None
    for offset, species in enumerate(days):
        if not species:
            continue
        top = species[0]
        if best is None or top["score"] > best["score"]:
            best = {
                "species_id":   top["id"],
                "species":      top["name"],
                "scientific":   top["scientific"],
                "score":        top["score"],
                "label":        top["label"],
                "day_offset":   offset,
                "date":         dates[offset] if offset < len(dates) else None,
            }
    return best or {}


def score_zone(zone, station, weather, dates, enrichment=None, weather_elevation=None,
               xema=None, water_series=None):
    """Score one curated zone with its own altitude, geo sample and enrichment.

    The zone fetches its own weather at its centroid (Phase 4.1) and lapse-
    corrects the temperature from the model/grid altitude `weather_elevation` to
    the curated `alt_m` (~6.5 °C/km). Precipitation, wind and humidity are shared
    with the parent massís; the altitude, the IGME/CORINE sample and (in Phase
    3.5) the terrain/canopy enrichment change per zone. The scoring formula is the
    same `score_station` used for stations, extended with the habitat (H) and
    microclimate (M) factors when an enrichment block is present, so zone and
    station scores remain comparable.

    When a Meteocat XEMA context is passed (Phase 4.2, key configured and API
    reachable), the result also carries a `xema` block of interpolated *observed*
    conditions. It annotates — never replaces — the Open-Meteo weather, so the
    score stays identical with or without Meteocat.

    Phase 4.3: `water_series` is the daily P + ET0 series for the zone centroid
    (from `fetch_water_batch`). When it yields a usable balance, the result
    carries a `water` block (14/30/60/90-day P−ET0 balances, recharge/drought
    index, state, documented XEMA blend info) and the rain score term is scaled
    by the per-species drought/recharge modifier. Without the series — or
    without ET0 — the `water` key is absent and the score is byte-identical to
    the previous phase (nothing is fabricated).
    """
    lat = float(zone["lat"])
    lon = float(zone["lon"])
    alt_m = zone.get("alt_m", station.get("alt_m", 900))
    lapse_c = None
    if weather_elevation is not None and alt_m is not None:
        try:
            lapse_c = round((float(alt_m) - float(weather_elevation))
                            * LAPSE_RATE_C_PER_M, 2)
        except (TypeError, ValueError):
            lapse_c = None
        weather = lapse_correct(weather, weather_elevation, alt_m)
    zone_station = {
        "name":  zone.get("name") or zone.get("id") or station["name"],
        "lat":   lat,
        "lon":   lon,
        "alt_m": alt_m,
        "_enrichment":       enrichment or {},
        "_confidence":       zone.get("confidence"),
        "_confidence_label": zone.get("confidence_label"),
    }
    geo = fetch_geo(lat, lon)
    water_block = compute_water_block(water_series, xema, lat, lon) \
        if water_series is not None else None
    # Phase 4.5: the same lapse-corrected daily payload feeds the GDD
    # phenology per species (no extra fetch; stations get phenology=None).
    days = [score_station(zone_station, weather, geo, day_offset=offset,
                          water=water_block, phenology=weather)
            for offset in range(7)]
    result = {
        "id":               zone.get("id"),
        "name":             zone.get("name"),
        "lat":              lat,
        "lon":              lon,
        "alt_m":            zone_station["alt_m"],
        "alt_range_m":      zone.get("alt_range_m"),
        "aspect_deg":       zone.get("aspect_deg"),
        "aspect":           zone.get("aspect"),
        "slope_deg":        zone.get("slope_deg"),
        "forest":           zone.get("forest"),
        "soil":             zone.get("soil"),
        "water_m":          zone.get("water_m"),
        "access":           zone.get("access"),
        "confidence":       zone.get("confidence"),
        "confidence_label": zone.get("confidence_label"),
        "sources":          zone.get("sources", []),
        "notes":            zone.get("notes", ""),
        "weather": {
            "grid_alt_m":         weather_elevation,
            "zone_alt_m":         alt_m,
            "lapse_correction_c": lapse_c,
        },
        "enrichment":       enrichment or {},
        "geo":              geo,
        "quality":          data_quality(weather, geo),
        "dates":            dates,
        "days":             days,
        "species":          days[0],
        "zone_score":       zone_score_summary(days, dates),
    }
    # Phase 4.2: observed XEMA conditions annotate the Open-Meteo forecast.
    # The key is only added when real station data is available, so the payload
    # without a Meteocat key is byte-identical to Phase 4.1.
    if xema is not None:
        xb = interpolate_xema(lat, lon, alt_m, xema)
        if xb is not None:
            result["xema"] = xb
    # Phase 4.3: soil water balance block (data + the rain-term modifier above).
    # Absent when the P−ET0 series is unusable — scoring then stays unchanged.
    if water_block is not None:
        result["water"] = water_block
    # Phase 4.5: per-zone phenology summary (GDD state per species, today).
    # Absent when the zone has no weather at all (degraded path keeps an
    # honest "no prediction" state; nothing is fabricated).
    if days and any(r.get("phenology") for r in days[0]):
        result["phenology"] = {
            "computed_at": date.today().isoformat(),
            "window_days": PHENO_WINDOW_DAYS,
            "alt_m":       alt_m,
            "note":        "suma tèrmica (GDD) dels últims 14 dies, corregida "
                           "per altitud amb el lapse rate 6,5 °C/km",
            "species":     {r["id"]: r["phenology"] for r in days[0]
                            if r.get("phenology")},
        }
    # Phase 4.4: per-zone data confidence — reporting only, never multiplied
    # into the score. Two distinct concepts: data completeness vs prediction
    # confidence (see README "Per-zone data confidence"). Per-species
    # confidence derives from the inputs each species' active scoring factors
    # depend on (documented preferences in mushrooms.json only).
    xema_block44 = result.get("xema")
    q44 = _conf_quality(zone, enrichment, geo, xema_block44)
    result["confidence"] = compute_zone_confidence(
        zone, enrichment, geo, xema_block44, water_block,
        water_series is not None)
    sp_defs = {s["id"]: s for s in SPECIES_LIST}
    for day_list in days:
        for sp_res in day_list:
            sp_def = sp_defs.get(sp_res.get("id"))
            if sp_def:
                sp_res["confidence"] = compute_species_confidence(
                    sp_def, geo, enrichment, water_block, q44)
    return result

# ── API handler ───────────────────────────────────────────────────────────────

def _apply_altitude_lag(output):
    """Fill `altitude_lag_days` per species across all zones (Phase 4.5).

    The wave front is the warmest zone of each species (highest `gdd_now`);
    every other zone lags it by ΔGDD divided by its own heat rate, estimated
    as gdd_now / window_days (°C·d per day) — the altitude lag in days.
    Zones with gdd_now below `PHENO_LAG_MIN_GDD` (effectively no heat; rate
    under ~0.2 °C·d/day) or a computed lag beyond `PHENO_LAG_MAX_DAYS` get
    None: the lag is not computable there (the wave will not reach/pass that
    altitude this season) and nothing is invented. Values are rounded to one
    decimal and mutate the per-species blocks in place (they are shared
    across days/zone blocks).
    """
    by_sp = {}
    for stns in output["comarques"].values():
        for stn in stns:
            for zone in stn.get("zones") or []:
                if zone.get("error"):
                    continue
                for r in zone.get("species") or []:
                    ph = r.get("phenology")
                    if not ph or ph.get("gdd_now") is None:
                        continue
                    by_sp.setdefault(r["id"], []).append(ph)
    for _sp_id, blocks in by_sp.items():
        warm_gdd = max(ph["gdd_now"] for ph in blocks)
        for ph in blocks:
            rate = ph["gdd_now"] / PHENO_WINDOW_DAYS
            if ph["gdd_now"] < PHENO_LAG_MIN_GDD:
                ph["altitude_lag_days"] = None
            else:
                lag = (warm_gdd - ph["gdd_now"]) / rate
                ph["altitude_lag_days"] = round(lag, 1) \
                    if lag <= PHENO_LAG_MAX_DAYS else None


def build_forecast():
    """Run full forecast for all stations. Returns structured dict."""
    output = {
        "date":    date.today().isoformat(),
        "comarques": {}
    }

    stations = get_stations()
    zones_by_station = get_zones()
    enrichment_by_id = _enrichment_lookup()

    def process_zones(station, dates, xema_ctx):
        """Score every curated zone for a station; one failure cannot hide others."""
        results = []
        for zone in zones_by_station.get(station["name"], []) or []:
            try:
                daily, elev = zone_weather(zone)
                if daily is None:
                    raise RuntimeError("meteo no disponible")
                results.append(score_zone(
                    zone, station, daily, dates,
                    enrichment=enrichment_by_id.get(zone.get("id")),
                    weather_elevation=elev, xema=xema_ctx,
                    water_series=zone_water(zone)))
            except Exception as e:
                results.append({
                    "id":       zone.get("id"),
                    "name":     zone.get("name"),
                    "lat":      zone.get("lat"),
                    "lon":      zone.get("lon"),
                    "alt_m":    zone.get("alt_m", station.get("alt_m")),
                    "sources":  zone.get("sources", []),
                    "error":    str(e),
                    "geo":      {},
                    "quality":  {"pct": 0, "label": "baixa", "reasons": ["error de dades"]},
                    "days":     [[] for _ in range(7)],
                    "dates":    dates,
                    "species":  [],
                    "zone_score": {},
                    # Phase 4.4: honest degraded confidence — a zone with an
                    # error has no scored prediction.
                    "confidence": {
                        "computed_at": date.today().isoformat(),
                        "completeness_pct": 0,
                        "completeness": {"weather": False},
                        "level": "baixa",
                        "score": None,
                        "field_reports": FIELD_REPORTS_COUNT,
                        "reasons": [{
                            "code": "no_weather", "impact": "−",
                            "label": "meteo no disponible · sense predicció",
                        }],
                    },
                })
        return results

    def zone_metadata(zone, station, xema_ctx=None):
        """Zone object with geo/alt metadata but no weather scores (degraded)."""
        lat = float(zone["lat"]); lon = float(zone["lon"])
        try:
            geo = fetch_geo(lat, lon)
        except Exception:
            geo = {}
        result = {
            "id":               zone.get("id"),
            "name":             zone.get("name"),
            "lat":              lat,
            "lon":              lon,
            "alt_m":            zone.get("alt_m", station.get("alt_m")),
            "alt_range_m":      zone.get("alt_range_m"),
            "aspect_deg":       zone.get("aspect_deg"),
            "aspect":           zone.get("aspect"),
            "slope_deg":        zone.get("slope_deg"),
            "forest":           zone.get("forest"),
            "soil":             zone.get("soil"),
            "water_m":          zone.get("water_m"),
            "access":           zone.get("access"),
            "confidence":       zone.get("confidence"),
            "confidence_label": zone.get("confidence_label"),
            "sources":          zone.get("sources", []),
            "notes":            zone.get("notes", ""),
            "enrichment":       enrichment_by_id.get(zone.get("id")) or {},
            "geo":              geo,
            "quality":          {"pct": 0, "label": "baixa", "reasons": ["meteo no disponible"]},
            "dates":            [],
            "days":             [[] for _ in range(7)],
            "species":          [],
            "zone_score":       {},
            "weather_unavailable": True,
            # Phase 4.4: honest degraded confidence — no weather means no
            # prediction at all (completeness 0, never fabricated).
            "confidence": {
                "computed_at": date.today().isoformat(),
                "completeness_pct": 0,
                "completeness": {"weather": False},
                "level": "baixa",
                "score": None,
                "field_reports": FIELD_REPORTS_COUNT,
                "reasons": [{
                    "code": "no_weather", "impact": "−",
                    "label": "meteo no disponible · sense predicció",
                }],
            },
        }
        if xema_ctx is not None:
            xb = interpolate_xema(
                lat, lon, zone.get("alt_m", station.get("alt_m")), xema_ctx)
            if xb is not None:
                result["xema"] = xb
        return result

    def process_station(comarca, station, weather, xema_ctx):
        try:
            if weather is None:
                raise RuntimeError("meteo no disponible")
            geo     = fetch_geo(station["lat"], station["lon"])
            # Score all 7 forecast days (0=today … 6=day+6)
            days = []
            for offset in range(7):
                species = score_station(station, weather, geo, day_offset=offset)
                days.append(species)
            # Derive forecast dates from weather time array
            dates = weather.get("time", [])[-7:]
            return comarca, {
                "name":    station["name"],
                "lat":     station["lat"],
                "lon":     station["lon"],
                "alt_m":   station["alt_m"],
                "radius_m": station.get("radius_m", 2000),
                "notes":   station.get("notes", ""),
                "geo":     geo,
                "quality": data_quality(weather, geo),
                "days":    days,    # list[7] of species lists
                "dates":   dates,   # list[7] of ISO date strings
                "species": days[0], # today — kept for backward compat
                "zones":   process_zones(station, dates, xema_ctx),
            }
        except Exception as e:
            return comarca, {
                "name":    station["name"],
                "lat":     station["lat"],
                "lon":     station["lon"],
                "alt_m":   station["alt_m"],
                "radius_m": station.get("radius_m", 2000),
                "notes":   station.get("notes", ""),
                "error":   str(e),
                "weather_unavailable": True,
                "geo":     {},
                "quality": {"pct": 0, "label": "baixa", "reasons": ["error de dades"]},
                "days":    [[] for _ in range(7)],
                "dates":   [],
                "species": [],
                "zones":   [zone_metadata(z, station, xema_ctx)
                            for z in (zones_by_station.get(station["name"], []) or [])],
            }

    all_tasks = []
    for comarca, stns in stations.items():
        output["comarques"][comarca] = []
        for stn in stns:
            all_tasks.append((comarca, stn))

    # Fetch weather for every station AND every zone centroid in ONE batched
    # Open-Meteo call (Phase 4.1). Zone centroids get their own local weather,
    # and `score_zone` lapse-corrects the temperature to the curated altitude.
    coords = [(s["lat"], s["lon"]) for _, s in all_tasks]
    for zone_list in zones_by_station.values():
        for z in zone_list:
            coords.append((z["lat"], z["lon"]))
    weather_by_coord = fetch_weather_batch(coords)

    # Phase 4.3: one batched P + ET0 series for the soil water balance, for the
    # same coordinates (cached per coordinate + calendar day in the same
    # weather_cache.json). Missing/empty entries degrade to "no water block".
    water_by_coord = fetch_water_batch(coords)

    # Phase 4.2: optional Meteocat XEMA observations (one fetch per forecast,
    # cached; None when METEOCAT_API_KEY is not set or the API is unreachable).
    # Open-Meteo always remains the fallback and the source of the 7-day
    # forecast; the XEMA data only annotates zones, never the score.
    xema_ctx = get_xema_context()
    if METEOCAT_API_KEY:
        if xema_ctx is not None:
            output["xema"] = {
                "status": "ok",
                "fetched_at": xema_ctx["fetched_at"],
                "stations_operatives": len(xema_ctx["stations"]),
            }
        else:
            output["xema"] = {
                "status": "error",
                "reason": last_xema_error() or "unknown",
            }

    def station_daily(station):
        w = weather_by_coord.get((station["lat"], station["lon"]))
        return w["daily"] if w else None

    def zone_weather(zone):
        """(daily, grid_elevation) for a zone centroid, or (None, None)."""
        w = weather_by_coord.get((zone["lat"], zone["lon"]))
        if not w:
            return None, None
        return w.get("daily"), w.get("elevation")

    def zone_water(zone):
        """Daily P + ET0 series for a zone centroid, or None (Phase 4.3)."""
        return water_by_coord.get((zone["lat"], zone["lon"]))

    with ThreadPoolExecutor(max_workers=6) as ex:
        futures = {ex.submit(process_station, c, s, station_daily(s), xema_ctx): (c, s)
                   for c, s in all_tasks}
        results_map = {c: [] for c in stations}
        for fut in as_completed(futures):
            comarca, data = fut.result()
            results_map[comarca].append(data)

    # Preserve station order
    for comarca, stns in stations.items():
        station_names = [s["name"] for s in stns]
        ordered = sorted(results_map[comarca],
                         key=lambda x: station_names.index(x["name"])
                         if x["name"] in station_names else 99)
        output["comarques"][comarca] = ordered

    # Phase 4.5: altitude lag across zones (wave front = warmest zone per
    # species). Mutates the shared per-species phenology blocks in place.
    _apply_altitude_lag(output)

    return output

