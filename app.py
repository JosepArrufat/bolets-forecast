def _xema_get(path, params=None):
    """One Meteocat API call with the X-Api-Key header. Returns parsed JSON.

    The docs (Seguretat + Python example) require the alphanumeric API Key in
    the `X-Api-Key` HTTP header; all dates returned by the API are UTC ISO 8601.
    """
    url = METEOCAT_BASE_URL + path
    if params:
        url += "?" + urllib.parse.urlencode(params)
    req = urllib.request.Request(
        url,
        headers={
            "User-Agent": "BoletsForecast/1.0",
            "Content-Type": "application/json",
            "X-Api-Key": METEOCAT_API_KEY,
        },
    )
    with urllib.request.urlopen(req, timeout=8) as r:
        return json.loads(r.read())


def _parse_xema_stations(payload):
    """Normalise the station-metadata array to {code: {nom, lat, lon, alt_m}}.

    Only stations currently operative are kept: the latest `estats` entry
    (the one with `dataFi: null`) must have `codi == 2` (operativa). Verified
    against the live API on 2026-11-08: 182 of 188 state-2 stations report
    readings and 0 of 57 state-1 (clausurada) stations do. Stations with no
    `estats` history at all are kept — a reading-bearing station is harmless,
    and a silent one is skipped later by the interpolation anyway.
    """
    out = {}
    for st in (payload if isinstance(payload, list) else []):
        if not isinstance(st, dict):
            continue
        try:
            latest = None
            for e in (st.get("estats") or []):
                if isinstance(e, dict) and e.get("dataFi") is None:
                    latest = e
            if latest is not None and latest.get("codi") != 2:
                continue
            coord = st.get("coordenades") or {}
            out[st["codi"]] = {
                "nom": st.get("nom"),
                "lat": float(coord["latitud"]),
                "lon": float(coord["longitud"]),
                "alt_m": st.get("altitud"),
            }
        except (KeyError, TypeError, ValueError):
            continue
    return out


def _parse_xema_readings(payload, stat_key="lectures"):
    """Normalise XEMA measured/statistic responses to {code: [readings]}.

    The docs show three response shapes, all handled here:
      - single station:  {"codi": "UG", "lectures": [...]}
      - all stations:    [{"codi": "C7", "variables": [{"codi": 3,
                           "lectures": [...]}]}, ...]
      - daily statistics: [{"codiEstacio": "C6", "codiVariable": 1300,
                           "valors": [...]}, ...]
    `stat_key` is "lectures" for measured data and "valors" for the daily
    statistics resources.
    """
    out = {}
    for item in (payload if isinstance(payload, list) else [payload]):
        if not isinstance(item, dict):
            continue
        code = item.get("codi") or item.get("codiEstacio")
        if not isinstance(code, str):
            continue
        readings = item.get(stat_key)
        if readings is None:
            for var in item.get("variables") or []:
                if isinstance(var, dict) and isinstance(var.get(stat_key), list):
                    readings = var[stat_key]
                    break
        if isinstance(readings, list):
            out[code] = readings
    return out


def _xema_reading_value(reading):
    """(value, iso_ts) for a trustworthy reading, else None.

    XEMA state codes (docs): 'V' valid, 'T' pending validation, 'N' invalid,
    ' ' not started. Only 'N' is dropped. Live `ultimes` data on 2026-11-08
    carried `estat: " "` on 100 % of the 183+186 real readings (semi-hourly
    provisional data is blank-labelled by design), so blank must be accepted
    or the feature would silently return nothing in production. Daily
    statistics carry a `percentatge` data-coverage field; values below 70 %
    are non-representative per Meteocat's open-data rules and are dropped too.
    """
    try:
        val = reading.get("valor")
        if val is None:
            return None
        estat = reading.get("estat")
        if isinstance(estat, str) and estat.strip() == "N":
            return None
        pct = reading.get("percentatge")
        if pct is not None:
            try:
                if float(pct) < 70.0:
                    return None
            except (TypeError, ValueError):
                pass
        return (float(val), str(reading.get("data") or ""))
    except (TypeError, ValueError):
        return None


def _xema_ts_to_epoch(ts_str):
    """UTC epoch seconds from an ISO 8601 timestamp ('...T09:00Z' or '...Z')."""
    try:
        dt = datetime.fromisoformat(ts_str.replace("Z", "+00:00"))
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        return dt.timestamp()
    except (ValueError, TypeError):
        return None


def _xema_stations_map():
    """{code: meta} for operative XEMA stations, cached 24 h."""
    global _xema_stations
    now = time.time()
    if (_xema_stations
            and now - _xema_stations.get("t", 0) < METEOCAT_STATIONS_TTL):
        return _xema_stations["stations"]
    stations = _parse_xema_stations(
        _xema_get("/xema/v1/estacions/metadades", {"codiEstacio": "TOTES"}))
    _xema_stations = {"t": now, "stations": stations}
    return stations


def _xema_latest(var_code):
    """{station_code: (value, iso_ts)} — last reading of one variable (4 h)."""
    payload = _xema_get(f"/xema/v1/variables/mesurades/{var_code}/ultimes")
    out = {}
    for code, readings in _parse_xema_readings(payload).items():
        best = None
        for rd in readings:
            v = _xema_reading_value(rd)
            if v and (best is None or v[1] > best[1]):
                best = v
        if best:
            out[code] = best
    return out


def _xema_daily_map():
    """{station_code: {"YYYY-MM-DD": mm}} accumulated daily precipitation."""
    global _xema_daily
    now = time.time()
    today = date.today().isoformat()
    if (_xema_daily and now - _xema_daily.get("t", 0) < METEOCAT_DAILY_TTL
            and _xema_daily.get("day") == today):
        return _xema_daily["data"]
    payload = _xema_get(
        f"/xema/v1/variables/estadistics/diaris/{XEMA_VAR_PPTDAY}",
        {"any": date.today().year, "mes": date.today().month})
    data = {}
    for code, readings in _parse_xema_readings(
            payload, stat_key="valors").items():
        for rd in readings:
            v = _xema_reading_value(rd)
            if not v:
                continue
            day = (str(rd.get("data") or ""))[:10]  # "YYYY-MM-DDZ" -> date
            if len(day) == 10:
                data.setdefault(code, {})[day] = v[0]
    _xema_daily = {"t": now, "day": today, "data": data}
    return data


def get_xema_context():
    """Meteocat XEMA observations for one forecast run, or None.

    Returns None — and makes **zero** Meteocat HTTP calls — when
    `METEOCAT_API_KEY` is not configured, keeping the app byte-identical to the
    Open-Meteo-only behaviour. When the key is set, stations metadata, the
    latest temperature/precipitation readings (last 4 h) and the current
    month's daily precipitation are fetched once per forecast (each cached:
    24 h / 15 min / 1 h) under one lock. Any Meteocat error returns None and is
    recorded in `last_xema_error()` — the Open-Meteo path keeps working.
    """
    global _xema_last_error, _xema_obs
    if not METEOCAT_API_KEY:
        return None
    with _xema_lock:
        now = time.time()
        try:
            stations = _xema_stations_map()
            obs = _xema_obs
            if not obs or now - obs.get("t", 0) >= METEOCAT_OBS_TTL:
                obs = {"t": now,
                       "temp": _xema_latest(XEMA_VAR_TEMP),
                       "ppt": _xema_latest(XEMA_VAR_PPT)}
                _xema_obs = obs
            daily = _xema_daily_map()
            _xema_last_error = None
            return {
                "stations": stations,
                "temp": obs["temp"],
                "ppt": obs["ppt"],
                "ppt_day": daily,
                "fetched_at": datetime.now(timezone.utc)
                    .strftime("%Y-%m-%dT%H:%M:%SZ"),
            }
        except Exception as e:  # noqa: BLE001 — fall back to Open-Meteo only
            _xema_last_error = str(e)
            return None


def last_xema_error():
    """Reason the last Meteocat fetch failed, or None."""
    return _xema_last_error


def interpolate_xema(lat, lon, zone_alt_m, ctx):
    """IDW interpolation of XEMA observations to a point; None when no data.

    Uses the nearest `XEMA_MAX_STATIONS` operative stations within
    `XEMA_RADIUS_KM` (great-circle distance from the station metadata lat/lon).
    Weights are inverse-distance squared, so the nearest station dominates.
    Temperatures are first lapse-corrected from each station's metadata
    altitude to `zone_alt_m` with the same 6.5 °C/km constant as the Open-Meteo
    correction (deterministic, documented); precipitation is **not**
    altitude-corrected (no simple lapse relationship — inventing one would
    fabricate data). Timestamps are the XEMA measurement labels (UTC,
    forward-labelled: an 11:00Z label covers 11:00–11:30Z).

    Returns the `xema` block for a zone, or None when no usable reading is
    available (the Open-Meteo-only payload stays untouched).
    """
    stations = (ctx or {}).get("stations") or {}
    candidates = []
    for code, meta in stations.items():
        try:
            d_km = haversine_m(lat, lon, meta["lat"], meta["lon"]) / 1000.0
        except (TypeError, ValueError, KeyError):
            continue
        if d_km <= XEMA_RADIUS_KM:
            candidates.append((code, meta, d_km))
    candidates.sort(key=lambda t: t[2])
    if not candidates:
        return None
    used = candidates[:XEMA_MAX_STATIONS]

    def idw(code_to_val):
        w_sum = v_sum = 0.0
        for code, _meta, d in used:
            v = code_to_val.get(code)
            if v is None:
                continue
            w = 1.0 / max(d, 0.5) ** 2   # 0.5 km floor avoids degenerate weights
            w_sum += w
            v_sum += w * v
        return (v_sum / w_sum) if w_sum > 0 else None

    # Temperatures: lapse-correct each station reading to the zone altitude.
    temp_vals = {}
    for code, meta, _d in used:
        t = ctx.get("temp", {}).get(code)
        if not t:
            continue
        val = t[0]
        try:
            if meta.get("alt_m") is not None and zone_alt_m is not None:
                val -= (float(zone_alt_m) - float(meta["alt_m"])) * LAPSE_RATE_C_PER_M
        except (TypeError, ValueError):
            pass
        temp_vals[code] = val

    ppt_vals = {code: ctx.get("ppt", {}).get(code, [None])[0]
                for code, _m, _d in used
                if ctx.get("ppt", {}).get(code)}

    # Daily accumulated precipitation (variable 1300): IDW per calendar day
    # (shared with the Phase-4.3 water-balance blend via `_xema_daily_idw`).
    day_vals = _xema_daily_idw(lat, lon, ctx)

    temp_c = idw(temp_vals)
    ppt_last = idw(ppt_vals)
    if temp_c is None and ppt_last is None:
        return None

    now_utc = datetime.now(timezone.utc).timestamp()
    station_rows = []
    ages = []
    for code, meta, d in used:
        freshest = None
        for bucket in (ctx.get("temp", {}), ctx.get("ppt", {})):
            t = bucket.get(code)
            if t and t[1]:
                e = _xema_ts_to_epoch(t[1])
                if e and (freshest is None or e > freshest):
                    freshest = e
        age_min = (int(round((now_utc - freshest) / 60.0))
                   if freshest is not None else None)
        if age_min is not None:
            ages.append(age_min)
        station_rows.append({
            "codi": code,
            "nom": meta.get("nom"),
            "distance_km": round(d, 1),
            "alt_m": meta.get("alt_m"),
            "age_min": age_min,
        })

    today = date.today().isoformat()
    seven = [(date.today() - timedelta(days=i)).isoformat()
             for i in range(6, -1, -1)]  # today-6 .. today (7 days)
    last7 = [day_vals.get(d) for d in seven if d in day_vals]
    block = {
        "source": "Meteocat XEMA (estacions automàtiques)",
        "fetched_at": ctx.get("fetched_at"),
        "temp_c": round(temp_c, 1) if temp_c is not None else None,
        "precip_last_mm": round(ppt_last, 1) if ppt_last is not None else None,
        "precip_today_mm": round(day_vals[today], 1) if today in day_vals else None,
        "precip_7d_mm": round(sum(last7), 1) if last7 else None,
        "precip_7d_days": len(last7),
        "nearest_distance_km": round(used[0][2], 1),
        "data_age_min": min(ages) if ages else None,
        "stations": station_rows,
    }
    return block

