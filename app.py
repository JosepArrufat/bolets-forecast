class Handler(BaseHTTPRequestHandler):

    def log_message(self, fmt, *args):
        print(f"  {self.address_string()} {fmt % args}")

    def send_json(self, data, status=200):
        body = json.dumps(data, ensure_ascii=False).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", len(body))
        self.end_headers()
        self.wfile.write(body)

    def send_html(self, html_str):
        body = html_str.encode()
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", len(body))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        path = self.path.split("?")[0]

        if path in ("/", "/index.html"):
            self.send_html(HTML)

        elif path == "/api/forecast":
            try:
                data = build_forecast()
                self.send_json(data)
            except Exception as e:
                self.send_json({"error": str(e)}, 500)

        elif path == "/api/stations":
            self.send_json(STATIONS)

        elif path == "/api/geocode":
            try:
                qs = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query)
                results = geocode_place(qs.get("q", [""])[0])
                self.send_json({"query": qs.get("q", [""])[0], "results": results})
            except Exception as e:
                self.send_json({"results": [], "error": str(e)}, 502)

        elif path == "/api/parking":
            try:
                qs = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query)
                lat = float(qs.get("lat", [""])[0])
                lon = float(qs.get("lon", [""])[0])
                self.send_json({"results": find_parking(lat, lon)})
            except Exception as e:
                self.send_json({"results": [], "error": str(e)}, 502)

        elif path == "/api/reports":
            try:
                qs = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query)
                bbox = None
                if "bbox" in qs:
                    parts = qs["bbox"][0].split(",")
                    if len(parts) != 4:
                        raise ValueError("bbox must be south,west,north,east")
                    south, west, north, east = (float(p) for p in parts)
                    bbox = (south, west, north, east)
                days = None
                if "days" in qs:
                    days = qs["days"][0]
                self.send_json(query_reports(bbox=bbox, days=days))
            except Exception as e:
                self.send_json({"reports": [], "total": 0, "error": str(e)}, 400)

        else:
            self.send_response(404)
            self.end_headers()

    def _read_body(self):
        try:
            length = int(self.headers.get("Content-Length") or 0)
        except ValueError:
            length = 0
        if length <= 0 or length > 1_000_000:
            return b""
        return self.rfile.read(length)

    def do_POST(self):
        path = self.path.split("?")[0]
        if path == "/api/reports":
            self._handle_post_report()
        else:
            self.send_response(404)
            self.end_headers()

    def do_DELETE(self):
        path = self.path.split("?")[0]
        if path != "/api/reports":
            self.send_response(404)
            self.end_headers()
            return
        self._handle_delete_report()

    def _handle_post_report(self):
        raw = self._read_body()
        try:
            body = json.loads(raw.decode("utf-8") or "{}")
        except Exception:
            self.send_json({"error": "invalid JSON body"}, 400)
            return

        try:
            data = _norm_report(body)
        except ValueError as e:
            self.send_json({"error": str(e)}, 400)
            return

        ip = self.client_address[0] or "0.0.0.0"
        device_hash = _resolve_device_hash(
            (body.get("device_id") if isinstance(body, dict) else None),
            ip, self.headers)
        ip_hash = _sha24(ip)

        report_id, breach = add_report(data, device_hash, ip_hash)
        if breach:
            self.send_json({"error": "rate_limited", "reason": breach}, 429)
            return

        self.send_json({
            "status": "ok",
            "id": report_id,
            "cell": {"lat": data["cell_lat"], "lon": data["cell_lon"]},
        }, 201)

    def _handle_delete_report(self):
        raw = self._read_body()
        body = {}
        if raw:
            try:
                body = json.loads(raw.decode("utf-8") or "{}")
            except Exception:
                body = {}
        if not isinstance(body, dict):
            body = {}

        ip = self.client_address[0] or "0.0.0.0"
        device_hash = _resolve_device_hash(
            (body.get("device_id") if isinstance(body, dict) else None),
            ip, self.headers)

        qs = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query)
        report_id = None
        if "id" in qs:
            try:
                report_id = int(qs["id"][0])
            except ValueError:
                self.send_json({"error": "id must be an integer"}, 400)
                return

        deleted, status = delete_reports(device_hash, report_id=report_id)
        if status == "not_found":
            self.send_json({"status": "not_found", "deleted": 0}, 404)
        elif status == "forbidden":
            self.send_json({"status": "forbidden", "deleted": 0}, 403)
        else:
            self.send_json({"status": "ok", "deleted": deleted})

