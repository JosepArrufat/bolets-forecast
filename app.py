# Prediction-confidence label thresholds (documented modelling choice).
CONF_LEVEL_THRESHOLDS = ((0.70, "alta"), (0.50, "mitjana"), (0.0, "baixa"))


def _conf_quality(zone, enrichment, geo, xema_block):
    """Deterministic per-input quality q (0–1) from sourced data only.

    xema returns None when the block is absent: its weight redistributes over
    the remaining inputs (documented graceful degradation) instead of scoring
    a missing pipeline.
    """
    enrich = enrichment or {}
    terr = (enrich.get("terrain") or {})
    can  = (enrich.get("canopy") or {})
    soil = (enrich.get("soil") or {})
    hab  = (enrich.get("habitat") or {})

    q = {"weather": Q_WEATHER, "reports": 0.0}

    # Curation: the zone's own curated confidence (0.6 "medium" for the 66
    # shipped zones, sourced in zones.json).
    conf = zone.get("confidence")
    q["curation"] = (float(conf)
                     if isinstance(conf, (int, float)) else Q_INPUT_MISSING)

    # Terrain: resolution of the DEM the terrain factors actually use.
    dem_src = terr.get("dem_source") or terr.get("source") or ""
    if terr.get("dem_aspect_deg") is not None or terr.get("source"):
        q["terrain"] = (Q_TERRAIN_LIDAR if "LiDAR" in dem_src
                        else Q_TERRAIN_COPERNICUS)
    else:
        q["terrain"] = Q_INPUT_MISSING

    # Canopy: the LiDAR sample-coverage fraction is itself the quality.
    cov = can.get("sample_coverage")
    q["canopy"] = (float(cov)
                   if isinstance(cov, (int, float)) and 0 <= cov <= 1
                   else Q_INPUT_MISSING)

    # Soil: IGME lithology with/without the SoilGrids pH sample.
    if soil.get("type"):
        q["soil"] = (Q_SOIL_FULL if soil.get("ph") is not None
                     else Q_SOIL_LITHO_ONLY)
    else:
        q["soil"] = Q_INPUT_MISSING

    # Forest/habitat: CORINE CLC 2018 (100 m).
    if hab.get("corine_code") or (geo or {}).get("forest_code"):
        q["forest"] = Q_HABITAT_CORINE
    else:
        q["forest"] = Q_INPUT_MISSING

    # XEMA: deterministic function of nearest-station distance + data age.
    if xema_block:
        d = xema_block.get("nearest_distance_km")
        age = xema_block.get("data_age_min")
        d_q = (max(0.0, min(1.0, 1.0 - float(d) / XEMA_RADIUS_KM))
               if isinstance(d, (int, float)) else 0.0)
        a_q = (max(0.0, min(1.0, 1.0 - float(age) / XEMA_AGE_ZERO_MIN))
               if isinstance(age, (int, float)) else 0.0)
        q["xema"] = round(0.6 * d_q + 0.4 * a_q, 3)
    else:
        q["xema"] = None
    return q


def _conf_impact(q):
    """+ / · / − impact code for a quality value (documented thresholds)."""
    if q is None:
        return "·"
    if q >= 0.70:
        return "+"
    if q > 0.45:
        return "·"
    return "−"


